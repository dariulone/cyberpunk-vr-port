//! RED4ext.SDK's `Detail/AddressHashes.hpp` as Rust constants: the one list of engine functions both the C++ DLL and
//! the Rust crates resolve through RED4ext (`RED4ext_ResolveAddress`). Regenerated, never edited by hand.
use crate::Result;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

pub fn parse(text: &str) -> Result<Vec<(String, u32)>> {
    let mut out = Vec::new();
    for (line_no, line) in text.lines().enumerate() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("constexpr std::uint32_t ") else { continue };
        let (name, value) = rest
            .split_once('=')
            .ok_or_else(|| format!("line {}: no '=' in {line}", line_no + 1))?;
        // A comment may follow the ';'.
        let value = value.split(';').next().unwrap_or("").trim();
        let value = value.trim_end_matches("UL").trim_end_matches('U');
        let parsed = if let Some(hex) = value.strip_prefix("0x").or_else(|| value.strip_prefix("0X")) {
            u32::from_str_radix(hex, 16)
        } else {
            value.parse::<u32>()
        }
        .map_err(|e| format!("line {}: {value}: {e}", line_no + 1))?;
        out.push((name.trim().to_string(), parsed));
    }
    if out.is_empty() {
        return Err("no address hashes found".into());
    }
    Ok(out)
}

pub fn run(input: &Path, output: &Path) -> Result {
    let text = fs::read_to_string(input).map_err(|e| format!("{}: {e}", input.display()))?;
    let hashes = parse(&text)?;
    let mut rs = String::new();
    rs.push_str("// @generated by `cvr-tool sdk-hashes` from RED4ext.SDK include/RED4ext/Detail/AddressHashes.hpp.\n");
    rs.push_str("// The engine addresses RED4ext resolves for a plugin (RED4ext_ResolveAddress). Do not edit.\n");
    rs.push_str("#![allow(non_upper_case_globals, dead_code)]\n\n");
    for (name, value) in &hashes {
        writeln!(rs, "pub const {name}: u32 = 0x{value:08X};").unwrap();
    }
    fs::write(output, rs).map_err(|e| format!("{}: {e}", output.display()))?;
    println!("{} hashes -> {}", hashes.len(), output.display());
    Ok(())
}

#[cfg(test)]
mod tests {
    #[test]
    fn parses_hex_and_decimal() {
        let v = super::parse(
            "constexpr std::uint32_t A = 0xA00C9B;\n  constexpr std::uint32_t B_c = 409015031UL;\n// x\n",
        )
        .unwrap();
        assert_eq!(v, vec![("A".into(), 0xA00C9B), ("B_c".into(), 409015031)]);
    }
}
