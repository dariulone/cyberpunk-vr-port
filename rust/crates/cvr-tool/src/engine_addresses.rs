//! The engine address table for Rust, generated from the headers the C++ half compiles against:
//! include/Stereo/EngineRvas.hpp (the verified RVAs) and include/Core/GameBuild.hpp (the build they belong to and the
//! addresses remap.py could not carry over). One source, checked on both sides: tools/patchday rewrites the headers,
//! this regenerates the Rust table, and cvr-engine's test fails when the two disagree.
use crate::Result;
use std::fmt::Write as _;
use std::fs;
use std::path::Path;

fn parse_int(value: &str) -> Result<u64> {
    let v = value.trim().trim_end_matches(['u', 'U', 'l', 'L']);
    if let Some(hex) = v.strip_prefix("0x").or_else(|| v.strip_prefix("0X")) {
        u64::from_str_radix(&hex.replace('\'', ""), 16).map_err(|e| format!("{value}: {e}"))
    } else {
        v.replace('\'', "").parse().map_err(|e| format!("{value}: {e}"))
    }
}

pub struct Table {
    pub rvas: Vec<(String, u64)>,
    pub version: String,
    pub timestamp: u64,
    pub size_of_image: u64,
    pub exe_sha256: String,
    pub unmapped: Vec<u64>,
}

pub fn parse(rvas_hpp: &str, build_hpp: &str) -> Result<Table> {
    let mut rvas: Vec<(String, u64)> = Vec::new();
    for (n, line) in rvas_hpp.lines().enumerate() {
        let line = line.trim();
        let Some(rest) = line.strip_prefix("constexpr uintptr_t ") else { continue };
        let err = |e: String| format!("EngineRvas.hpp:{}: {e}", n + 1);
        // `A = 0x10, B = 0x10 + 0x4` -- several declarators, each a sum of literals and earlier names.
        let body = rest.split(';').next().unwrap_or("");
        for declarator in body.split(',') {
            let (name, expr) = declarator.split_once('=').ok_or_else(|| err(format!("no '=' in {declarator}")))?;
            let mut value = 0u64;
            for term in expr.split('+').map(str::trim) {
                value += match rvas.iter().find(|(n, _)| n == term) {
                    Some((_, v)) => *v,
                    None => parse_int(term).map_err(err)?,
                };
            }
            rvas.push((name.trim().to_string(), value));
        }
    }
    let field = |key: &str| -> Result<String> {
        build_hpp
            .lines()
            .find_map(|l| {
                let l = l.trim();
                let pos = l.find(key)?;
                let after = l[pos + key.len()..].trim_start();
                let after = after.strip_prefix('=')?;
                Some(after.split(';').next().unwrap_or("").trim().to_string())
            })
            .ok_or_else(|| format!("GameBuild.hpp: no {key}"))
    };
    let unquote = |s: String| s.trim_matches('"').to_string();
    let mut unmapped = Vec::new();
    let mut inside = false;
    for line in build_hpp.lines() {
        let t = line.trim();
        if t.contains("BEGIN UNMAPPED") {
            inside = true;
            continue;
        }
        if t.contains("END UNMAPPED") {
            inside = false;
            continue;
        }
        if inside {
            for v in t.split(',').map(str::trim).filter(|v| !v.is_empty() && !v.starts_with("//")) {
                let v = parse_int(v)?;
                if v != 0 {
                    unmapped.push(v);
                }
            }
        }
    }
    Ok(Table {
        rvas,
        version: unquote(field("kVersion")?),
        timestamp: parse_int(&field("kTimestamp")?)?,
        size_of_image: parse_int(&field("kSizeOfImage")?)?,
        exe_sha256: unquote(field("kExeSha256")?),
        unmapped,
    })
}

pub fn render(t: &Table) -> String {
    let mut rs = String::new();
    rs.push_str("// @generated by `cvr-tool engine-addresses` from include/Stereo/EngineRvas.hpp and include/Core/GameBuild.hpp.\n");
    rs.push_str("// Do not edit: tools/patchday rewrites the headers, this file follows (cvr-engine's test checks it).\n");
    rs.push_str("#![allow(dead_code)]\n\n");
    rs.push_str("/// The Cyberpunk2077.exe every address below was verified against.\npub mod build {\n");
    writeln!(rs, "    pub const VERSION: &str = \"{}\";", t.version).unwrap();
    writeln!(rs, "    pub const TIMESTAMP: u32 = 0x{:08X};", t.timestamp).unwrap();
    writeln!(rs, "    pub const SIZE_OF_IMAGE: u32 = 0x{:08X};", t.size_of_image).unwrap();
    writeln!(rs, "    pub const EXE_SHA256: &str = \"{}\";", t.exe_sha256).unwrap();
    rs.push_str("    /// Addresses tools/patchday/remap.py could not carry to this build: still the old build's, refused.\n");
    rs.push_str("    pub const UNMAPPED: &[usize] = &[");
    rs.push_str(&t.unmapped.iter().map(|v| format!("0x{v:X}")).collect::<Vec<_>>().join(", "));
    rs.push_str("];\n}\n\n/// RVAs into Cyberpunk2077.exe (include/Stereo/EngineRvas.hpp, same names).\npub mod rva {\n");
    for (name, value) in &t.rvas {
        writeln!(rs, "    pub const {name}: usize = 0x{value:X};").unwrap();
    }
    rs.push_str("}\n");
    rs
}

pub fn run(rvas: &Path, build: &Path, out: &Path) -> Result {
    let a = fs::read_to_string(rvas).map_err(|e| format!("{}: {e}", rvas.display()))?;
    let b = fs::read_to_string(build).map_err(|e| format!("{}: {e}", build.display()))?;
    let table = parse(&a, &b)?;
    fs::write(out, render(&table)).map_err(|e| format!("{}: {e}", out.display()))?;
    println!("{} RVAs, build {} {:08X} -> {}", table.rvas.len(), table.version, table.timestamp, out.display());
    Ok(())
}
