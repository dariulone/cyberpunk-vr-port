//! The world markers' vertex shaders for the Rust build (world_marker_shader.rs embeds them): src/Render/WorldMarkers.hlsl
//! compiled by DXC exactly as cmake/EmbedWorldMarkerShaders.cmake compiles it for the reference build (`-T vs_6_0 -E
//! <variant>Main -O3`), with the compiler CMake found (CVR_DXC, which cmake/RustStaticlib.cmake passes) or else the
//! newest Windows SDK's. Only the rust-build feature needs them; other builds of the crate skip the step.
use std::fmt::Write as _;
use std::path::PathBuf;
use std::process::Command;

/// The variants in the table's order (world_marker_shader.rs `plugin::TABLE`).
const VARIANTS: [&str; 6] = ["Sprite", "Procedural", "SpriteStereo", "TextStereo", "SpriteStereoZ", "SpriteStereoOne"];

fn dxc() -> PathBuf {
    if let Some(path) = std::env::var_os("CVR_DXC") {
        return path.into();
    }
    let root = PathBuf::from(r"C:\Program Files (x86)\Windows Kits\10\bin");
    let mut found: Vec<PathBuf> = std::fs::read_dir(&root)
        .into_iter()
        .flatten()
        .flatten()
        .map(|entry| entry.path().join("x64").join("dxc.exe"))
        .filter(|path| path.is_file())
        .collect();
    found.sort();
    found.pop().expect("dxc.exe: set CVR_DXC or install the Windows SDK")
}

fn main() {
    println!("cargo:rerun-if-changed=build.rs");
    println!("cargo:rerun-if-env-changed=CVR_DXC");
    if std::env::var_os("CARGO_FEATURE_RUST_BUILD").is_none() {
        return;
    }
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let source = manifest.join("..").join("..").join("..").join("src").join("Render").join("WorldMarkers.hlsl");
    println!("cargo:rerun-if-changed={}", source.display());
    let out = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    let dxc = dxc();
    let mut table = String::from(
        "// Generated by build.rs: the world markers' DXIL, 16-byte aligned as the reference build's arrays.\n\
         #[repr(C, align(16))]\npub struct Aligned<const N: usize>(pub [u8; N]);\n",
    );
    for variant in VARIANTS {
        let binary = out.join(format!("{variant}.dxil"));
        let output = Command::new(&dxc)
            .args(["-T", "vs_6_0", "-E", &format!("{variant}Main"), "-O3", "-Fo"])
            .arg(&binary)
            .arg(&source)
            .output()
            .expect("dxc could not be started");
        assert!(
            output.status.success(),
            "World marker {variant} shader failed: {}{}",
            String::from_utf8_lossy(&output.stdout),
            String::from_utf8_lossy(&output.stderr)
        );
        let size = std::fs::metadata(&binary).unwrap().len();
        writeln!(
            table,
            "pub static {}: Aligned<{size}> = Aligned(*include_bytes!({:?}));",
            variant.to_uppercase(),
            binary.display().to_string()
        )
        .unwrap();
    }
    std::fs::write(out.join("world_marker_dxil.rs"), table).unwrap();
}
