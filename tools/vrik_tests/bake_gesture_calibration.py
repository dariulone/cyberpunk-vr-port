"""Bake the user's right-hand local corrections after verifying mirror axes."""
import argparse
import hashlib
import json
import math
import struct
from pathlib import Path

ROOT=Path(__file__).resolve().parents[2]
FIXTURES=Path(__file__).parent/'fixtures'
SOURCE=FIXTURES/'gesture-calibration.json'
OUTPUT=ROOT/'include/Anim/HandGestureCalibration.hpp'

def mul(a,b):
    x,y,z,w=a;X,Y,Z,W=b
    return [w*X+x*W+y*Z-z*Y,w*Y-x*Z+y*W+z*X,w*Z+x*Y-y*X+z*W,w*W-x*X-y*Y-z*Z]
def norm(q):
    n=math.sqrt(sum(v*v for v in q));assert n>1e-9
    return [v/n for v in q]
def inverse(q):return [-q[0],-q[1],-q[2],q[3]]
def rotate(q,v):return mul(mul(q,[*v,0]),inverse(q))[:3]
def load_rotations(folder):
    names=[line.split('\t')[-1]for line in (folder/'player_names.txt').read_text().splitlines()]
    parents=struct.unpack('<'+'h'*len(names),(folder/'player_parents.bin').read_bytes())
    poses=list(struct.iter_unpack('<12f',(folder/'reference_full.bin').read_bytes()));out=[]
    for i,row in enumerate(poses):out.append(norm(mul(out[parents[i]],row[4:8]) if parents[i]>=0 else row[4:8]))
    return dict(zip(names,out))
def radians_delta(row):
    p,y,r=[math.radians(row[k])*.5 for k in ('pitch','yaw','roll')]
    return norm(mul(mul([0,0,math.sin(y),math.cos(y)],[math.sin(p),0,0,math.cos(p)]),[0,math.sin(r),0,math.cos(r)]))
def generate():
    data=json.loads(SOURCE.read_text());assert data['version']==1
    rows=[];worst=0
    rigs=[load_rotations(FIXTURES/rig)for rig in ('','gorilla','mantis','launcher')]
    for pose,key in enumerate(('three','fist','thumb','index')):
        for name,row in sorted(data['poses'][key]['right'].items()):
            q=norm(row['delta']);expected=radians_delta(row)
            assert abs(sum(a*b for a,b in zip(q,expected)))>1-1e-10,(key,name,'export quaternion disagrees with angles')
            if max(abs(v) for v in q[:3])<1e-8:continue
            assert name.startswith('Right');suffix=name[5:]
            for rig in rigs:
                left,right=rig['Left'+suffix],rig[name]
                # Reflection S=diag(-1,1,1). Quaternion vectors are axial:
                # qLeft.xyz = -RLeft^T S RRight qRight.xyz. On these canonical
                # finger bind frames that map is identity, despite mirrored arms.
                for axis in ([1,0,0],[0,1,0],[0,0,1]):
                    v=rotate(right,axis);v[0]=-v[0];mapped=[-x for x in rotate(inverse(left),v)]
                    error=max(abs(a-b)for a,b in zip(mapped,axis));worst=max(worst,error)
                    assert error<.0001,(name,'finger frame is not mirror-compatible',mapped)
                v=rotate(right,q[:3]);v[0]=-v[0];mirrored=[-x for x in rotate(inverse(left),v)]+[q[3]]
                assert abs(sum(a*b for a,b in zip(norm(mirrored),q)))>1-1e-8
            rows.append((pose,suffix,3,q))
    def literal(x):
        text=f'{x:.9g}';return text+('' if '.' in text or 'e' in text else '.0')+'f'
    lines=['#pragma once','// Exported from: tools/vrik_tests/fixtures/gesture-calibration.json.',
           '// Generated by bake_gesture_calibration.py. Right-hand corrections;',
           '// canonical bind axes verified for both hands on four native rigs.',
           'namespace cvr::gestures {',
           'struct GestureCalibration {int pose;const char* suffix;unsigned hands;float delta[4];};',
           f'inline constexpr char GestureCalibrationSource[]="{hashlib.sha256(SOURCE.read_bytes()).hexdigest()}";',
           'inline constexpr GestureCalibration CalibratedGestures[]={']
    for pose,suffix,hands,q in rows:lines.append('    {'+str(pose)+',"'+suffix+'",'+str(hands)+',{'+','.join(map(literal,q))+'}},')
    lines+=['};','}']
    return '\n'.join(lines)+'\n',len(rows),worst
if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--check',action='store_true');args=p.parse_args()
    text,count,error=generate()
    if args.check:assert OUTPUT.read_text()==text,'Baked header differs from saved user export'
    else:OUTPUT.write_text(text)
    print(f'PASS: {count} authored corrections, four rig mirror checks; max axis error {error:.3g}')
