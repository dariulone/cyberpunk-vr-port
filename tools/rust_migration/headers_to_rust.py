"""Transcribes the generated pose tables the C++ half keeps in headers into Rust (rust/crates/cvr-rig/src/data.rs):
the native fist and the baked gesture corrections (include/Anim/HandGesturePose.hpp, HandGestureCalibration.hpp), the
mantis blades' deployed assembly (MantisDeployment.hpp) and the cyberware muscle curves (CyberwareMuscles.hpp).

Every number is copied as its decimal text (less the `f` suffix), so the Rust compiler rounds it to the same float the
C++ compiler did. Rerun after the Python generators of those headers change:  python headers_to_rust.py"""
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|[{},]|[-+]?(?:\d+\.?\d*|\.\d+)(?:[eE][-+]?\d+)?f?|[A-Za-z_]\w*')


def initializer(text, name):
    """The brace initializer of `name` in a header, as nested lists of str (strings keep their quotes)."""
    match = re.search(r'\b' + re.escape(name) + r'\s*(?:\[[^\]]*\])*\s*=\s*', text)
    if not match:
        raise SystemExit(f'{name}: not found')
    tokens = TOKEN.findall(text[match.end():])
    def parse(i):
        if tokens[i] != '{':
            return tokens[i], i + 1
        items, i = [], i + 1
        while tokens[i] != '}':
            item, i = parse(i)
            items.append(item)
            if tokens[i] == ',':
                i += 1
        return items, i + 1
    value, _ = parse(0)
    return value


def f32(token):
    """A float literal for Rust: the same decimal text, an integer given a fraction."""
    t = token[:-1] if token.endswith('f') else token
    if not re.search(r'[.eE]', t):
        t += '.0'
    return t


def floats(value):
    if isinstance(value, list):
        return '[' + ', '.join(floats(v) for v in value) + ']'
    return f32(value)


def main():
    pose = (REPO / 'include/Anim/HandGesturePose.hpp').read_text(encoding='utf-8')
    calibration = (REPO / 'include/Anim/HandGestureCalibration.hpp').read_text(encoding='utf-8')
    mantis = (REPO / 'include/Anim/MantisDeployment.hpp').read_text(encoding='utf-8')
    muscles = (REPO / 'include/Anim/CyberwareMuscles.hpp').read_text(encoding='utf-8')
    out = ['//! Generated by tools/rust_migration/headers_to_rust.py from include/Anim/HandGesturePose.hpp,',
           '//! HandGestureCalibration.hpp, MantisDeployment.hpp and CyberwareMuscles.hpp -- do not edit; regenerate.',
           '//! The numbers are those headers\' decimal texts, rounded to f32 by the compiler as the C++ ones were.',
           '#![allow(clippy::excessive_precision, clippy::approx_constant)]', '']
    out += ['/// A native Gorilla attack finger local: the fist and the reference pose per hand ([0] left, [1] right).',
            'pub struct FingerPose { pub suffix: &\'static str, pub group: usize, pub closed: [[f32; 4]; 2], pub reference: [[f32; 4]; 2] }',
            'pub static NATIVE_FIST: [FingerPose; %d] = [' % len(initializer(pose, 'NativeFist'))]
    for suffix, group, closed, reference in initializer(pose, 'NativeFist'):
        out.append(f'    FingerPose {{ suffix: {suffix}, group: {group}, closed: {floats(closed)}, reference: {floats(reference)} }},')
    out += ['];', '']
    source = initializer(calibration, 'GestureCalibrationSource') if False else re.search(
        r'GestureCalibrationSource\[\]\s*=\s*("[^"]*")', calibration).group(1)
    out += [f'pub const GESTURE_CALIBRATION_SOURCE: &str = {source};',
            '/// A baked per-hand gesture correction: pose 0..3, the finger suffix, the hands (bit 0 left, 1 right), the delta.',
            'pub struct GestureCalibration { pub pose: usize, pub suffix: &\'static str, pub hands: u32, pub delta: [f32; 4] }',
            'pub static CALIBRATED_GESTURES: [GestureCalibration; %d] = [' % len(initializer(calibration, 'CalibratedGestures'))]
    for p, suffix, hands, delta in initializer(calibration, 'CalibratedGestures'):
        out.append(f'    GestureCalibration {{ pose: {p}, suffix: {suffix}, hands: {hands}, delta: {floats(delta)} }},')
    out += ['];', '']
    bones = initializer(mantis, 'MantisDeployment')
    out += ['/// The mantis blades\' deployed assembly, in the frame of the Hand (+Y the forearm axis, +Z the dorsal normal).',
            'pub struct MantisDeploymentBone { pub name: &\'static str, pub position: [f32; 3], pub rotation: [f32; 4] }',
            'pub static MANTIS_DEPLOYMENT: [MantisDeploymentBone; %d] = [' % len(bones)]
    for name, position, rotation in bones:
        out.append(f'    MantisDeploymentBone {{ name: {name}, position: {floats(position)}, rotation: {floats(rotation)} }},')
    out += ['];',
            f'pub const MANTIS_DEPLOYMENT_REFERENCE_LENGTH: [f32; 2] = {floats(initializer(mantis, "MantisDeploymentReferenceLength"))};',
            f'pub const MANTIS_DEPLOYMENT_WRIST_ANCHOR: [[f32; 3]; 2] = {floats(initializer(mantis, "MantisDeploymentWristAnchor"))};', '']
    count = int(re.search(r'MuscleSampleCount\s*=\s*(\d+)', muscles).group(1))
    curves = initializer(muscles, 'MuscleCurves')
    out += [f'pub const MUSCLE_SAMPLE_COUNT: usize = {count};',
            'pub struct MuscleSample { pub position: [f32; 3], pub rotation: [f32; 4], pub scale: [f32; 3] }',
            'pub struct MuscleCurve { pub name: &\'static str, pub family: i32, pub samples: [MuscleSample; MUSCLE_SAMPLE_COUNT] }',
            'pub static MUSCLE_CURVES: [MuscleCurve; %d] = [' % len(curves)]
    for name, family, samples in curves:
        if len(samples) != count:
            raise SystemExit(f'{name}: {len(samples)} samples')
        out.append(f'    MuscleCurve {{ name: {name}, family: {family}, samples: [')
        for position, rotation, scale in samples:
            out.append(f'        MuscleSample {{ position: {floats(position)}, rotation: {floats(rotation)}, scale: {floats(scale)} }},')
        out.append('    ] },')
    out += ['];', '']
    target = REPO / 'rust/crates/cvr-rig/src/data.rs'
    target.write_text('\n'.join(out), encoding='utf-8', newline='\n')
    print(f'{target}: {len(initializer(pose, "NativeFist"))} fist fingers, {len(bones)} mantis bones, {len(curves)} muscle curves')


if __name__ == '__main__':
    sys.exit(main())
