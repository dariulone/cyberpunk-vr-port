static Json Describe(const Mesh& mesh){
    Vec3 lo=mesh.vertices.front(),hi=lo;
    for(const auto& v:mesh.vertices){lo.x=std::min(lo.x,v.x);lo.y=std::min(lo.y,v.y);lo.z=std::min(lo.z,v.z);hi.x=std::max(hi.x,v.x);hi.y=std::max(hi.y,v.y);hi.z=std::max(hi.z,v.z);}
    return {{"vertices",mesh.vertices.size()},{"triangles",mesh.triangles.size()},{"chunks",mesh.chunks},{"lod",mesh.lod},{"minimum",{lo.x,lo.y,lo.z}},{"maximum",{hi.x,hi.y,hi.z}},{"round_profile",LatheProfile(mesh)}};
}
static int Batch(const char* library,const char* manifest,const char* destination){
    Oodle oodle(library);std::ifstream input(manifest);std::ofstream output(destination);
    Require(bool(input)&&bool(output),"cannot open batch manifest/output");
    size_t done=0,failed=0;std::string line;const auto start=std::chrono::steady_clock::now();
    while(std::getline(input,line)){
        if(line.empty())continue;
        const auto source=Json::parse(line);Json result={{"path",source.at("path")},{"hash",source.at("hash")},{"archive",source.at("archive")}};
        try {
            Cr2w cooked(source.at("source").get<std::string>());
            result.update(Describe(DecodeMesh(cooked,oodle)));result["status"]="ok";
        } catch(const std::exception& e){++failed;result["status"]="error";result["error"]=e.what();}
        output<<result.dump()<<'\n';Require(bool(output),"batch output failed");++done;
        if(done%1000==0){output.flush();std::cout<<done<<" meshes, "<<failed<<" errors, "<<std::chrono::duration<double>(std::chrono::steady_clock::now()-start).count()<<" seconds\n"<<std::flush;}
    }
    std::cout<<"complete: "<<done<<" meshes, "<<failed<<" errors\n";return failed?1:0;
}
static int EmitProfiles(const char* catalog,const char* destination){
    struct Record {Json profile;std::string path;bool ambiguous{};};
    std::map<uint64_t,Record> records;std::ifstream input(catalog);Require(bool(input),"cannot open profile catalog");
    std::string line;size_t candidates=0,duplicates=0,ambiguous=0;
    while(std::getline(input,line)){
        if(line.empty())continue;const auto row=Json::parse(line);
        if(row.at("status")!="ok"||!row.contains("round_profile")||row.at("round_profile").is_null())continue;
        ++candidates;const auto hashText=row.at("hash").get<std::string>();uint64_t hash{};
        const auto parsed=std::from_chars(hashText.data(),hashText.data()+hashText.size(),hash,16);
        Require(parsed.ec==std::errc{}&&parsed.ptr==hashText.data()+hashText.size(),"invalid depot hash");
        const auto& profile=row.at("round_profile");const int axis=profile.at("axis").get<int>();
        Require(axis>=0&&axis<=2&&profile.at("radii").size()==16,"invalid radial profile");
        const auto [it,inserted]=records.emplace(hash,Record{profile,row.at("path").get<std::string>(),false});
        if(!inserted){++duplicates;if(it->second.profile!=profile)it->second.ambiguous=true;}
    }
    std::ofstream output(destination);Require(bool(output),"cannot create profile include");
    output<<"// Generated by tools/grip_generator from decoded cooked meshes; do not edit.\n"
        "// Archive variants with different profiles are excluded; their source records remain in the catalog.\n";
    output<<std::scientific<<std::setprecision(9);
    size_t emitted=0;
    for(const auto& [hash,record]:records){
        if(record.ambiguous){++ambiguous;continue;}
        const auto& profile=record.profile;
        output<<"{0x"<<std::hex<<std::setw(16)<<std::setfill('0')<<hash<<std::dec<<std::setfill(' ')<<"ull, "<<profile.at("axis").get<int>();
        for(const char* field:{"low","high","center_b","center_c"}){const float v=profile.at(field).get<float>();Require(std::isfinite(v),"non-finite profile coordinate");output<<", "<<v<<'f';}
        output<<", {";for(size_t i=0;i<16;++i){const float r=profile.at("radii").at(i).get<float>();Require(std::isfinite(r)&&r>=0,"invalid profile radius");if(i)output<<", ";output<<r<<'f';}
        auto path=record.path;for(char& c:path)if(c=='\r'||c=='\n')c=' ';
        output<<"}}, // "<<path<<'\n';++emitted;
    }
    Require(bool(output),"profile include write failed");
    std::cout<<Json{{"candidate_versions",candidates},{"same_hash_versions",duplicates},{"ambiguous_hashes_excluded",ambiguous},{"emitted",emitted}}.dump()<<'\n';return 0;
}
int main(int argc,char** argv){
    try {
        if(argc==4&&std::string_view(argv[1])=="--emit-profiles")return EmitProfiles(argv[2],argv[3]);
        if(argc==5&&std::string_view(argv[1])=="--batch")return Batch(argv[2],argv[3],argv[4]);
        if(argc==5&&std::string_view(argv[1])=="--verify"){
            Oodle oodle(argv[2]);Cr2w cooked(argv[3]);std::cout<<VerifyGlb(DecodeMesh(cooked,oodle),argv[4]).dump()<<'\n';return 0;
        }
        Require(argc>=4,"usage: grip_generator OODLE_DLL MESH OUTPUT_JSON [OUTPUT_OBJ]");
        Oodle oodle(argv[1]);Cr2w cooked(argv[2]);
        // Save the metadata too: a decoder failure remains inspectable.
        const auto header=cooked.Chunk("rendRenderMeshBlob");
        std::ofstream metadata(std::filesystem::path(argv[3]).replace_extension("header.json"));metadata<<header.dump(2);metadata.close();
        const auto mesh=DecodeMesh(cooked,oodle);
        Json report=Describe(mesh);report["source"]=argv[2];
        std::ofstream output(argv[3]);Require(bool(output),"cannot create output");output<<report.dump(2)<<'\n';
        if(argc>4){std::ofstream obj(argv[4]);Require(bool(obj),"cannot create OBJ");obj.precision(9);for(auto v:mesh.vertices)obj<<"v "<<v.x<<' '<<v.y<<' '<<v.z<<'\n';for(auto t:mesh.triangles)obj<<"f "<<t[0]+1<<' '<<t[1]+1<<' '<<t[2]+1<<'\n';}
        std::cout<<report.dump()<<'\n';return 0;
    } catch(const std::exception& e){std::cerr<<e.what()<<'\n';return 1;}
}
