"""Writes the size of weapon attachments for CyberpunkVRPort_HandCollision, from the game's own meshes.

Usage: python tools/emit_weapon_attachments.py <dir of serialized .mesh.json> <out .lua>

Serialize the meshes first: WolvenKit.CLI unbundle basegame_4_gamedata.archive -r 'w_att.*\\.mesh$', then convert serialize.

An attachment's mesh is in its own frame, at its mount, so only how far it reaches from there is used: the outline of the
weapon (weapon_boxes.lua) grows by it. { minX, maxX, minY, maxY, minZ, maxZ }, by the name its mesh components start with.
"""
import glob
import json
import os
import re
import sys

SKIP = re.compile(r"decal|shadow|glass|lens|_fx|lod\d", re.I)
NAME = re.compile(r"^(w_att_+[a-z]+(?:_[a-z]+)?_\d+)", re.I)

src, out = sys.argv[1], sys.argv[2]
boxes = {}
for path in glob.glob(os.path.join(src, "**", "*.json"), recursive=True):
    name = os.path.basename(path).split(".")[0]
    m = NAME.match(name)
    if not m or SKIP.search(name):
        continue
    with open(path, encoding="utf-8") as f:
        box = json.load(f)["Data"]["RootChunk"].get("boundingBox")
    if not box:
        continue
    lo, hi = box["Min"], box["Max"]
    v = [lo["X"], hi["X"], lo["Y"], hi["Y"], lo["Z"], hi["Z"]]
    if max(abs(x) for x in v) > 2.0:
        continue
    key = m.group(1).lower()
    b = boxes.setdefault(key, list(v))
    b[0], b[2], b[4] = min(b[0], v[0]), min(b[2], v[2]), min(b[4], v[4])
    b[1], b[3], b[5] = max(b[1], v[1]), max(b[3], v[3]), max(b[5], v[5])

lines = [
    "-- GENERATED by tools/emit_weapon_attachments.py from the game's meshes -- do not edit.",
    "--",
    "-- How far each weapon attachment reaches from its mount, metres: +Y along the barrel, +Z up.",
    "-- { minX, maxX, minY, maxY, minZ, maxZ }, by the name its mesh components start with.",
    "return {",
]
for key in sorted(boxes):
    lines.append("    %s = { %s }," % (key, ", ".join("%.4f" % x for x in boxes[key])))
lines.append("}")
with open(out, "w", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print("attachments", len(boxes))
for k in sorted(boxes):
    print(k, ["%.3f" % x for x in boxes[k]])
