"""Writes each weapon's collision shape for CyberpunkVRPort_HandCollision: a few boxes fitted to the game's own vertices.

Usage: python tools/emit_weapon_shapes.py <dir of serialized .mesh.json> <out .lua>

A held weapon has no collider in the game: of 943 firearm meshes one has a physics parameter, a magazine's box, and no firearm entity
or appearance has a collider component. One box round a whole gun is mostly air (a pistol's is an L in a rectangle), so the gun is
cut into slices along its barrel, each slice boxed from its own vertices, and neighbours merged while that adds little volume.

The serialized mesh carries its vertex buffer: renderResourceBlob.renderBuffer.Bytes, base64. Stream 0 starts each vertex with the
position as four signed 16-bit normalised numbers, quantised by the header's quantizationScale and Offset. Skinned meshes are in bind
pose in the weapon's frame (origin at the grip, +Y along the barrel, +Z up), so the parts of one weapon simply add up.
"""
import base64
import glob
import json
import os
import re
import struct
import sys

SKIP = re.compile(r"decal|shadow|mag_stdr|mag_ext|mag_drum|silencer|muzzle|scope|sight_|attachment|_fx|glass|lod\d|dying_night|neon|_d\d\d_|wilson|krausser|rook", re.I)
NAME = re.compile(r"^(w_[a-z0-9_]+?__[a-z0-9_]+?)__", re.I)
SLICES, MOST, GROW, THIN = 14, 6, 0.25, 0.008     # slices, boxes at most, how much bigger a merge may be, and the least half size kept

src, out = sys.argv[1], sys.argv[2]


def points_of(path):
    with open(path, encoding="utf-8") as f:
        root = json.load(f)["Data"]["RootChunk"]
    blob = root["renderResourceBlob"]["Data"]
    head = blob["header"]
    raw = base64.b64decode(blob["renderBuffer"]["Bytes"])
    scale, offset = head["quantizationScale"], head["quantizationOffset"]
    pts = []
    for c in head["renderChunkInfos"]:
        if not c.get("lodMask", 1) & 1:
            continue
        n = c["numVertices"]
        offs = c["chunkVertices"]["byteOffsets"]["Elements"]
        if n == 0:
            continue
        layout = c["chunkVertices"]["vertexLayout"]["elements"]["Elements"]
        first = layout[0]
        if first.get("usage") != "PS_Position" or first.get("type") != "PT_Short4N":
            raise ValueError("layout %s %s" % (first.get("usage"), first.get("type")))
        stride = (offs[1] - offs[0]) // n
        if stride < 8:
            raise ValueError("stride %d" % stride)
        for i in range(n):
            x, y, z = struct.unpack_from("<hhh", raw, offs[0] + i * stride)
            pts.append((x / 32767.0 * scale["X"] + offset["X"], y / 32767.0 * scale["Y"] + offset["Y"], z / 32767.0 * scale["Z"] + offset["Z"]))
    return pts


def box_of(pts):
    return [min(p[0] for p in pts), max(p[0] for p in pts), min(p[1] for p in pts), max(p[1] for p in pts), min(p[2] for p in pts), max(p[2] for p in pts)]


def volume(b):
    return max(b[1] - b[0], 2 * THIN) * max(b[3] - b[2], 2 * THIN) * max(b[5] - b[4], 2 * THIN)


def union(a, b):
    return [min(a[0], b[0]), max(a[1], b[1]), min(a[2], b[2]), max(a[3], b[3]), min(a[4], b[4]), max(a[5], b[5])]


def fit(pts):
    all_box = box_of(pts)
    lo, hi = all_box[2], all_box[3]
    step = (hi - lo) / SLICES
    buckets = [[] for _ in range(SLICES)]
    for p in pts:
        buckets[min(SLICES - 1, int((p[1] - lo) / step))].append(p)
    boxes = []
    for i, b in enumerate(buckets):
        if b:
            bx = box_of(b)
            # the slice's whole length: neighbours must meet, or a thin thing could stand between them
            bx[2], bx[3] = lo + i * step, lo + (i + 1) * step
            boxes.append(bx)
    while len(boxes) > 1:
        best, cost = None, None
        for i in range(len(boxes) - 1):
            v = volume(boxes[i]) + volume(boxes[i + 1])
            c = volume(union(boxes[i], boxes[i + 1])) / v
            if cost is None or c < cost:
                best, cost = i, c
        if len(boxes) <= MOST and cost > 1.0 + GROW:
            break
        boxes[best:best + 2] = [union(boxes[best], boxes[best + 1])]
    return boxes, all_box


families = {}
counts = {}
bad = 0
for path in glob.glob(os.path.join(src, "**", "*.json"), recursive=True):
    name = os.path.basename(path).split(".")[0]
    m = NAME.match(name)
    if not m or SKIP.search(name):
        continue
    try:
        pts = points_of(path)
    except (KeyError, ValueError, TypeError, struct.error) as e:
        bad += 1
        print("skipped", name, e)
        continue
    if not pts:
        continue
    b = box_of(pts)
    if max(abs(x) for x in b) > 3.0:
        continue
    key = m.group(1).lower()
    families.setdefault(key, []).extend(pts[::2] if len(pts) > 20000 else pts)
    counts[key] = counts.get(key, 0) + 1

lines = [
    "-- GENERATED by tools/emit_weapon_shapes.py from the vertices of the game's meshes -- do not edit.",
    "--",
    "-- Each weapon as a few boxes in its own frame: origin at the grip, +Y along the barrel, +Z up, metres.",
    "-- { minX, maxX, minY, maxY, minZ, maxZ }, by the name its mesh components start with.",
    "return {",
]
report = []
for key in sorted(families):
    boxes, whole = fit(families[key])
    lines.append("    %s = {" % key)
    for b in boxes:
        lines.append("        { %s }," % ", ".join("%.4f" % x for x in b))
    lines.append("    },")
    filled = sum(volume(b) for b in boxes) / volume(whole)
    report.append((key, counts[key], len(boxes), filled, whole))
lines.append("}")
with open(out, "w", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print("weapons", len(report), "skipped meshes", bad)
print("mean boxes %.1f, mean share of the outline they fill %.2f" % (sum(r[2] for r in report) / len(report), sum(r[3] for r in report) / len(report)))
for r in report[:4] + report[-4:]:
    print(r[0], "parts", r[1], "boxes", r[2], "fills %.2f" % r[3], ["%.3f" % x for x in r[4]])
