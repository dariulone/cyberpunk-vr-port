#include "Runtimes/CyberFingerMenuPolicy.hpp"
#include <stdexcept>
#include <iostream>
using namespace cvr::cyberfinger;
void Check(bool value,const char* message){if(!value)throw std::runtime_error(message);}
int main()try {
    MenuNavigation menu;
    auto s=menu.Step(true,1,0,1,true,true,100);
    Check(!s.direction && !s.tab && !s.back,"held entry controls activated menu");
    menu.Step(true,0,0,0,false,false,120);
    s=menu.Step(true,0,1,-1,true,false,130);
    Check(s.direction==1 && s.tab==-1 && s.back && s.grabMask==1,"physical navigation mapping");
    s=menu.Step(true,0,1,-1,true,false,300);
    Check(!s.direction && !s.tab && !s.back,"held tab/back repeats");
    s=menu.Step(true,0,1,-1,true,false,550);
    Check(s.direction==1 && !s.tab && !s.back,"arrow repeat without repeated tab/back");
    menu.Step(false,0,0,0,false,false,600);
    s=menu.Step(true,0,1,-1,true,false,610);
    Check(!s.direction && !s.tab && !s.back,"context switch carried held input");
    menu.Step(true,0,0,0,false,false,620);
    s=menu.Step(true,-1,0,1,false,true,630);
    Check(DirectionButton(s.direction)==4 && s.tab==1 && s.grabMask==2,"right back and left navigation");
    NativeMenuButtons native;
    Check(native.Step(true,false,true,true)==0,"held entry activated native menu");
    Check(native.Step(false,false,false,false)==0,"entry release generated Back");
    Check(native.Step(false,false,true,false)==0x4000,"left Grab is not X");
    Check(native.Step(false,false,true,false)==0x4000,"hold-X action was shortened to a pulse");
    Check(native.Step(false,false,false,true)==0x4000,"right Grab is not X");
    Check(native.Step(false,false,false,false)==0,"X remained held after release");
    Check(native.Step(true,false,false,false)==0,"Menu fired before release, breaking the chord");
    Check(native.Step(false,false,false,false)==0x2000,"left Menu release is not Back");
    native.Step(false,true,false,false);
    Check(native.Step(false,false,false,false)==0x2000,"right Menu release is not Back");
    native.Step(true,false,false,false);
    Check(native.Step(true,true,false,false)==0,"both Menu chord also exited native menu");
    Check(native.Step(false,true,false,false)==0,"partial chord release emitted Back");
    Check(native.Step(true,true,false,false)==0,"repressed chord emitted Back");
    Check(native.Step(false,false,false,false)==0,"chord release emitted Back");
    native.Step(true,false,false,false);
    Check(native.Step(false,false,false,false)==0x2000,"Menu failed to rearm after chord");
    MenuFocus focus;
    Check(!focus.Step(false,true,.5f,.5f),"ray should be default");
    Check(focus.Step(true,true,.5f,.5f),"stick should claim highlight");
    Check(focus.Step(false,true,.51f,.51f),"hand jitter stole highlight");
    Check(!focus.Step(false,true,.6f,.5f),"deliberate ray movement did not reclaim pointer");
    MenuTapHold button;
    Check(!button.Step(true,true,10).tap,"held entry menu button activated");
    button.Step(false,true,20);button.Step(true,true,30);
    Check(button.Step(false,true,80).tap,"inventory tap missing");
    button.Step(true,true,100);
    for(uint64_t t=200;t<=700;t+=100)Check(!button.Step(true,true,t).hold,"cyberware activated early");
    Check(button.Step(true,true,750).hold,"long press did not activate cyberware");
    Check(!button.Step(false,true,760).tap,"cyberware release also opened inventory");
    button.Step(true,true,800);button.Step(true,false,810);
    Check(!button.Step(false,true,820).tap,"menu context change emitted inventory");
    button.Step(true,true,900);
    Check(!button.Step(true,true,1700).hold,"pause counted as deliberate hold");
    Check(!button.Step(false,true,1710).tap,"pause replayed inventory tap");
    ToggleButton scanner;
    Check(!scanner.Step(true,true,10),"held startup toggles scanner");
    scanner.Step(true,false,20);Check(scanner.Step(true,true,30),"scanner press missing");
    Check(scanner.Step(true,false,40),"scanner required holding button");
    Check(!scanner.Step(true,true,50),"second scanner press did not close");
    scanner.Step(false,false,60);
    Check(!scanner.Step(true,true,70),"menu Back leaked into scanner");
    HudChord hud;
    Check(!hud.Step(true,true,true,.1f),"held entry HUD chord fired");
    hud.Step(false,false,true,.1f);
    for(int i=0;i<4;++i)Check(!hud.Step(true,true,true,.1f),"HUD toggle fired before half a second");
    Check(hud.Step(true,true,true,.1f) && hud.Claimed(),"HUD chord failed");
    Check(!hud.Step(true,true,true,.1f),"HUD chord repeated");
    hud.Step(false,true,true,.1f);Check(hud.Claimed(),"partial chord release leaked Menu action");
    for(int i=0;i<8;++i)Check(!hud.Step(true,true,true,.1f),"partial release rearmed HUD chord");
    hud.Step(false,false,true,.1f);Check(!hud.Claimed(),"released HUD chord stayed claimed");
    hud.Step(true,true,true,.2f);hud.Step(true,true,false,.2f);
    Check(!hud.Claimed() && !hud.Step(true,true,true,.2f),"tracking loss replayed HUD hold");
    ConversationNavigation conversation;
    Check(conversation.Step(true,1,1,100)==0,"controls held on dialogue entry activated a choice");
    conversation.Step(true,0,0,110);
    Check(conversation.Step(true,1,0,120)==1,"right stick did not select previous choice");
    conversation.Step(true,0,0,130);
    Check(conversation.Step(true,-1,0,140)==2,"right stick did not select next choice");
    Check(conversation.Step(true,0,1,150)==3,"right trigger did not confirm");
    Check(conversation.Step(true,0,.5f,160)==0,"trigger chatter confirmed twice");
    Check(conversation.Step(true,0,1,170)==0,"held trigger confirmed twice");
    conversation.Step(true,0,0,180);
    Check(conversation.Step(true,0,1,190)==3,"released right trigger did not rearm");
    conversation.Step(false,0,1,200);
    Check(conversation.Step(true,0,1,210)==0,"dialogue restart replayed confirm");
    std::cout<<"CyberFinger menu policy passed\n";
}catch(const std::exception& e){std::cerr<<e.what()<<'\n';return 1;}
