#include "Runtimes/CyberFingerHintBindings.hpp"
#include <stdexcept>

using namespace cvr::cyberfinger;
int main() {
    auto check = [](bool ok) { if (!ok) throw std::runtime_error("incorrect CF hint"); };
    check(PhysicalHintSource("Left Hand", "B (Menu: context dial) Click") == LeftMenu);
    check(PhysicalHintSource("Right Hand", "Grip (the grab button, as pressed)") == RightGrip);
    check(PhysicalHintSource("Left Hand", "Trigger Touch") == 0);
    check(PhysicalHintSource("Other", "Trigger") == 0);
    HintLayout s;
    s.seated = s.driving = s.exitGrip = s.defaultExitTime = true;
    check(ControlHint("EnterCombatMode", false, s).empty());
    s.sources = LeftMenu | LeftGrip;
    check(ControlHint("EnterCombatMode", false, s) == "Tap Left Menu");
    check(ControlHint("Exit", false, s) == "Hold Left Grip 0.4 s");
    s.exitGrip = false;
    check(ControlHint("Exit", true, s).empty());
    s.sources = ~0u;
    for (bool left : {false,true}) {
        s.leftWeapon = left;
        for (bool armed : {false,true}) {
            s.vehicleFire = armed;
            s.armed = armed;
            check(ControlHint("Accelerate", false, s) == "Right Stick Forward");
            check(ControlHint("Decelerate", false, s) == "Right Stick Back");
            check(ControlHint("ToggleVehCamera",false,s) == "Right Grip");
            check(ControlHint("RangedAttack", false, s) == (armed ? (left ? "Left Trigger" : "Right Trigger") : ""));
            check(ControlHint(armed?"CameraAim":"VehicleHorn",false,s) == (left?"Right Trigger":"Left Trigger"));
            check(ControlHint("UseConsumable",false,s) == "Hold Right Black Wrist");
        }
    }
    s.dialogue = true;
    check(ControlHint("ChoiceApply",false,s) == "Either Trigger or Right Stick Click");
    s.sources=RightStickClick;
    check(ControlHint("ChoiceApply",false,s) == "Right Stick Click");
    check(ControlHint("Accelerate",false,s).empty());
    s = {};
    s.sources = ~0u;
    s.leftWeapon = true;
    check(ControlHint("Reload", false, s).empty());
    s.firearm = true;
    check(ControlHint("Reload", false, s) == "Tap Right Black Wrist");
    s.leftWeapon = false;
    check(ControlHint("Reload", false, s) == "Tap Left Black Wrist");
    check(ControlHint("Choice1", false, s).empty());
    s.interaction = true;
    check(ControlHint("Choice1_Hold", false, s) == "Hold Right Trigger");
    s.leftMouse = true;
    check(ControlHint("Choice2", true, s) == "Hold Left Grip");
    s.dialogue = true;
    check(ControlHint("ChoiceApply", false, s) == "Either Trigger");
    s.sources=LeftTrigger;
    check(ControlHint("ChoiceApply", false, s) == "Left Trigger");
    s.sources=RightTrigger;
    check(ControlHint("ChoiceApply", false, s) == "Right Trigger");
    s.sources=0;
    check(ControlHint("ChoiceApply", false, s).empty());
    s.sources=~0u;
    check(ControlHint("Choice2", true, s).empty());
    check(ControlHint("Unknown", true, s).empty());
    check(PhysicalHintSource("Right","Joystick Click") == RightStickClick);
    check(PhysicalHintSource("Right","Joystick",true) == RightStickClick);
    check(PhysicalHintSource("Right","Joystick Position",true) == RightStick);
    s = {};
    s.sources = RightStick;
    s.driving = true;
    check(ControlHint("Handbrake",false,s).empty());
    s.sources |= RightStickClick;
    check(ControlHint("Handbrake",false,s) == "Right Stick Click");
    s = {};
    s.sources = ~0u;
    for (bool left : {false,true}) {
        s.leftWeapon = left;
        s.menu = true;
        s.context = MenuContext::ShardReader;
        check(ControlHint("cancel",false,s) == "Right Grip");
        s.context = MenuContext::Map;
        check(ControlHint("world_map_menu_zoom_in",false,s) == (left ? "Left Stick Up" : "Right Stick Up"));
        check(ControlHint("world_map_menu_jump_to_player",false,s) == (left ? "Right Trigger" : "Left Trigger"));
        check(ControlHint("world_map_menu_track_waypoint",false,s) == (left ? "Left Grip" : "Right Grip"));
        check(ControlHint("world_map_menu_open_quest",false,s) == (left ? "Right Grip" : "Left Grip"));
        check(ControlHint("next_menu",false,s) == "Right Stick Right");
        check(ControlHint("navigate_up",false,s).empty());
        check(ControlHint("RangedAttack",false,s).empty());
        s.context = MenuContext::Journal;
        check(ControlHint("sort_list",false,s) == (left ? "Right Trigger" : "Left Trigger"));
        check(ControlHint("click",false,s) == (left ? "Left Trigger" : "Right Trigger"));
        s.context = MenuContext::PictureFrame;
        check(ControlHint("UI_smart_frame_confirm",false,s) == "Either Trigger");
        check(ControlHint("UI_smart_frame_remove",false,s) == "Either Grip");
        s.context = MenuContext::General;
        check(ControlHint("preview_item",false,s) == "Either Grip");
        check(ControlHint("right_stick_y_scroll",false,s) == "Right Stick Up/Down");
        check(ControlHint("sort_list",false,s).empty());
        s.menu = false;
        s.leftMouse = left;
        s.computer = true;
        check(ControlHint("click",false,s) == (left ? "Left Trigger" : "Right Trigger"));
        check(ControlHint("StopDeviceControl",false,s) == "Either Menu");
        s.computer = false;
        s.scanner = true;
        check(ControlHint("UI_ApplyAndClose",false,s) == (left ? "Left Trigger" : "Right Trigger"));
        check(ControlHint("UI_MoveUp",false,s).empty());
        s.scanner = false;
        s.foot = Walking | (left ? MoveRight : 0);
        check(ControlHint("ToggleCrouch",false,s) == (left ? "Left Stick Back" : "Right Stick Back"));
        check(ControlHint("Dodge",false,s).empty());
        s.foot |= DashEnabled;
        check(ControlHint("Dodge",false,s) == (left ? "Left Stick Forward" : "Right Stick Forward"));
        s.melee = s.katana = s.secondGrip = true;
        s.leftSword = false;
        check(ControlHint("MeleeAttack",false,s) == "Fast swing / Left Grip at hilt for strong");
        s.leftSword = true;
        check(ControlHint("MeleeAttack",false,s) == "Fast swing / Right Grip at hilt for strong");
        s.dualKatana = true;
        check(ControlHint("MeleeAttack_Tutorial",false,s) == "Swing either katana");
        s.dualKatana = false;
    }
    s.leftSword = false;
    check(ControlHint("HolsterWeapon",false,s) == "Right Grip");
    s.leftSword = true;
    check(ControlHint("HolsterWeapon",false,s) == "Left Grip");
    s.dualKatana=true;
    check(ControlHint("HolsterWeapon",false,s) == "Grip on the sword to put away");
    s.leftSword=false;
    check(ControlHint("HolsterWeapon",false,s) == "Grip on the sword to put away");
    s.dualKatana=false;
    check(ControlHint("HolsterWeapon",false,s) == "Right Grip");
    s.katana=false;
    check(ControlHint("HolsterWeapon",false,s).empty());
    s.fists=true;check(ControlHint("MeleeBlock",false,s)=="Raise hands + hold both Triggers");
    s.fists=false;check(ControlHint("MeleeBlock",false,s).empty());
    s.foot = Walking | MoveRight;
    check(ControlHint("Sprint",false,s) == "Hold Right Stick Forward");
    s.foot |= ClickSprint;
    check(ControlHint("Sprint",false,s) == "Left Stick Click");
    check(ControlHint("CallVehicle",false,s) == "Hold Left Stick Click + Right Stick Right");
    s.menu = true;
    s.sources = LeftMenu | RightTrigger;
    check(ControlHint("back",false,s) == "Left Menu");
    check(ControlHint("click",false,s) == "Right Trigger");
    check(ControlHint("preview_item",false,s).empty());
}
