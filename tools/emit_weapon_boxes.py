"""Writes the weapons' real outlines for CyberpunkVRPort_HandCollision, from the game's own meshes.

Usage: python tools/emit_weapon_boxes.py <dir of serialized .mesh.json> <out .lua>

Serialize the meshes first: WolvenKit.CLI unbundle <archive> -r 'weapons.*firearms.*mesh$', then convert serialize.

A held weapon has no collider of its own in the game, so its shape is what is drawn: each mesh's bounding box, in the
weapon's frame (origin at the grip, +Y along the barrel, +Z up). Skinned meshes are in bind pose in that frame, so the
parts of one weapon can simply be added up. The extras are left out: a swapped magazine, a decal, a shadow proxy, a mod.
"""
import glob
import json
import os
import re
import sys

SKIP = re.compile(r"decal|shadow|mag_stdr|mag_ext|mag_drum|silencer|muzzle|scope|sight_|attachment|_fx|glass|lod\d", re.I)
NAME = re.compile(r"^(w_[a-z0-9_]+?__[a-z0-9_]+?)__", re.I)

src, out = sys.argv[1], sys.argv[2]
boxes = {}
parts = {}
for path in glob.glob(os.path.join(src, "**", "*.json"), recursive=True):
    name = os.path.basename(path).split(".")[0]
    m = NAME.match(name)
    if not m or SKIP.search(name):
        continue
    with open(path, encoding="utf-8") as f:
        box = json.load(f)["Data"]["RootChunk"].get("boundingBox")
    if not box:
        continue
    lo, hi = box["Min"], box["Max"]
    v = [lo["X"], hi["X"], lo["Y"], hi["Y"], lo["Z"], hi["Z"]]
    if not (hi["Y"] - lo["Y"] > 0.005) or max(abs(x) for x in v) > 3.0:
        continue
    key = m.group(1).lower()
    b = boxes.setdefault(key, list(v))
    b[0], b[2], b[4] = min(b[0], v[0]), min(b[2], v[2]), min(b[4], v[4])
    b[1], b[3], b[5] = max(b[1], v[1]), max(b[3], v[3]), max(b[5], v[5])
    parts[key] = parts.get(key, 0) + 1

lines = [
    "-- GENERATED by tools/emit_weapon_boxes.py from the game's meshes -- do not edit.",
    "--",
    "-- Each weapon's outline in its own frame: origin at the grip, +Y along the barrel, +Z up, metres.",
    "-- { minX, maxX, minY, maxY, minZ, maxZ }, by the name its mesh components start with.",
    "return {",
]
for key in sorted(boxes):
    lines.append("    %s = { %s }," % (key, ", ".join("%.4f" % x for x in boxes[key])))
lines.append("}")
with open(out, "w", newline="\r\n") as f:
    f.write("\n".join(lines) + "\n")
print("weapons", len(boxes))
long = sorted(boxes.items(), key=lambda kv: kv[1][3] - kv[1][2])
for k, b in long[:4] + long[-6:]:
    print(k, parts[k], ["%.3f" % x for x in b])
