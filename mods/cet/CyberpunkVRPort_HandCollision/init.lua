-- Translate a RIGID SET of capsules until none of them overlaps any obstacle, and return the translation.
local function resolveRig(side, movers, segs)
    if movers.n == 0 or segs.n == 0 then return 0.0, 0.0, 0.0 end
    local mem = stick[side]
    local tx, ty, tz = 0.0, 0.0, 0.0

    -- COARSE CULL: one sphere test per obstacle against the whole mover set. The pairwise pass below is
    -- movers x obstacles -- 74 x 90 with fingers and a 58-capsule weapon -- and no amount of slack tuning
    -- changes that product; measured, tightening the pairwise slack from 0.15 to 0.05 moved the pair count from
    -- 722 to 806, because the weapon had meanwhile gone from 28 capsules to 58. Culling the obstacles once does
    -- change it. Grown by CULL because this list is built once and must survive the whole hold, measured as far
    -- as 0.166 m.
    NEAR.n = 0
    local cx, cy, cz = 0.0, 0.0, 0.0
    for i = 1, movers.n do
        local m = movers[i]
        cx, cy, cz = cx + m.cx, cy + m.cy, cz + m.cz
    end
    local inv = 1.0 / movers.n
    cx, cy, cz = cx * inv, cy * inv, cz * inv
    local rad = 0.0
    for i = 1, movers.n do
        local m = movers[i]
        local dx, dy, dz = m.cx - cx, m.cy - cy, m.cz - cz
        local d = math.sqrt(dx * dx + dy * dy + dz * dz) + m.e
        if d > rad then rad = d end
    end
    rad = rad + CULL
    for i = 1, segs.n do
        local s = segs[i]
        local dx, dy, dz = s.cx - cx, s.cy - cy, s.cz - cz
        local reach = rad + s.e
        if dx * dx + dy * dy + dz * dz <= reach * reach then push(NEAR, s) end
    end
    if NEAR.n == 0 then return 0.0, 0.0, 0.0 end

    local n = 0
    local function broadphase()
        n = 0
        for mi = 1, movers.n do
            local m = movers[mi]
            local mx, my, mz = m.cx + tx, m.cy + ty, m.cz + tz
            local me, mid = m.e, m.id * 512
            for si = 1, NEAR.n do
                local s = NEAR[si]
                local dx, dy, dz = mx - s.cx, my - s.cy, mz - s.cz
                local reach = me + s.e + BROAD
                if dx * dx + dy * dy + dz * dz <= reach * reach then
                    n = n + 1
                    CD_M[n], CD_S[n], CD_KEY[n] = m, s, mid + s.id
                end
            end
        end
        if n > candMax then candMax = n end
        return n
    end

    if broadphase() == 0 then return 0.0, 0.0, 0.0 end
    local bx, by, bz = 0.0, 0.0, 0.0

    for _ = 1, PASSES do
        -- SEQUENTIAL PROJECTION: each contact is answered in full the moment it is found, and the next one is
        -- evaluated against the already-moved rig. Count-independent, unlike an average -- see cause 4.
        local deepest, dm, ds = 0.0, nil, nil
        for ci = 1, n do
            local m, s, key = CD_M[ci], CD_S[ci], CD_KEY[ci]
            local hx, hy, hz, qx, qy, qz = segClosest(
                m.ax + tx, m.ay + ty, m.az + tz, m.bx + tx, m.by + ty, m.bz + tz,
                s.ax, s.ay, s.az, s.bx, s.by, s.bz)
            local sx, sy, sz = hx - qx, hy - qy, hz - qz
            local dist = math.sqrt(sx * sx + sy * sy + sz * sz)
            local need = m.r + s.r
            local mm = mem[key]
            local limit = need
            if mm then limit = need + RELEASE_MARGIN end
            if dist >= limit then
                if mm then mem[key] = nil end
            else
                local ux, uy, uz
                if dist > 1e-5 then ux, uy, uz = sx / dist, sy / dist, sz / dist
                else ux, uy, uz = 0.0, 0.0, 1.0 end
                if mm then
                    -- keep leaving by the side it first left by; the shortest way out flips once the mover is
                    -- past the axis, and following that flip teleported the hand through the chest
                    if (mm[1] * ux + mm[2] * uy + mm[3] * uz) < 0.0 then
                        ux, uy, uz = mm[1], mm[2], mm[3]
                        dist = -(sx * ux + sy * uy + sz * uz)
                    end
                else
                    mem[key] = { ux, uy, uz }
                end
                local depth = need - dist
                if depth > 0.0 then
                    local step = depth * OMEGA
                    tx, ty, tz = tx + ux * step, ty + uy * step, tz + uz * step
                    if depth > deepest then deepest, dm, ds = depth, m, s end
                end
            end
        end
        if dm then worstM[side], worstS[side] = dm.label, ds.label end
        if deepest <= SETTLED then break end
        local ddx, ddy, ddz = tx - bx, ty - by, tz - bz
        if ddx * ddx + ddy * ddy + ddz * ddz > BROAD * BROAD * 0.25 then
            bx, by, bz = tx, ty, tz
            if broadphase() == 0 then break end
        end
    end
    return tx, ty, tz
end

-- WHICH HAND HOLDS THE WEAPON, latched for the life of that weapon instance. Decided per frame as "nearer wrist"
-- it flipped whenever the free hand came to the grip -- which is where the trigger is -- and each flip swapped
-- which hand was frozen. A weapon does not change hands while equipped.
local HOLDER_DROP = 0.30    -- m: beyond this from the grip, the latched hand plainly is not holding it
local holderSide, holderEnt = nil, nil
local dbgDL, dbgDR = -1.0, -1.0

-- WHICH HAND HOLDS THE GUN, asked of the game rather than guessed from geometry.
--
-- The distance test below picks whichever wrist is nearer the grip, and that is wrong exactly when it matters: a
-- hand reaching for the MAGAZINE passes closer to the grip than the hand holding the weapon. The holder then
-- flipped to the free hand -- the gun visibly snapped across to it (the pistol went under the left hand) and the
-- reload's magnet, which always drives the hand that is NOT the holder, started pulling the real gun hand.
--
-- The game already knows the answer: a held weapon is attached to `ItemAttachmentSlots.WeaponRight` or
-- `.WeaponLeft`, and `GetItemInSlot` returns it. Verified live -- the active weapon's entity id came back from
-- WeaponRight and from nowhere else. Cached per weapon, because it cannot change without the weapon changing.
local slotHolder, slotHolderFor = nil, nil
local function holderFromSlot()
    local pl = Game.GetPlayer()
    local w = pl and pl:GetActiveWeapon()
    if not w then slotHolder, slotHolderFor = nil, nil; return nil end
    local okId, wid = pcall(function() return w:GetEntityID().hash end)
    if not okId then return nil end
    if slotHolderFor == wid then return slotHolder end
    local ts = Game.GetTransactionSystem()
    if not ts then return nil end
    local found = nil
    for _, e in ipairs({ { 1, 'AttachmentSlots.WeaponRight' }, { 0, 'AttachmentSlots.WeaponLeft' } }) do
        local ok, it = pcall(function() return ts:GetItemInSlot(pl, TweakDBID.new(e[2])) end)
        if ok and it then
            local ok2, h = pcall(function() return it:GetEntityID().hash end)
            if ok2 and h == wid then found = e[1]; break end
        end
    end
    if found ~= nil then slotHolder, slotHolderFor = found, wid end
    return found
end

local function holderOf(rl, rr)
    -- the game's own answer wins; the geometry below is only for when it has none to give
    local s = holderFromSlot()
    if s ~= nil then
        holderSide, holderEnt = s, slotEnt
        local function d0(v)
            if not v then return -1.0 end
            local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
            return math.sqrt(dx * dx + dy * dy + dz * dz)
        end
        dbgDL, dbgDR = d0(rl), d0(rr)
        return s
    end
    if slotEnt ~= holderEnt then holderSide, holderEnt = nil, slotEnt end
    local function dist(v)
        local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
        return math.sqrt(dx * dx + dy * dy + dz * dz)
    end
    dbgDL = rl and dist(rl) or -1.0
    dbgDR = rr and dist(rr) or -1.0

    if holderSide ~= nil then
        local d = (holderSide == 0) and dbgDL or dbgDR
        if d >= 0.0 and d <= HOLDER_DROP then return holderSide end
        holderSide = nil
    end

    -- Right by default, and the left has to WIN by a margin. Cyberpunk holds a weapon in the right hand; the
    -- left is only ever a support hand, and it can sit as close to the grip as the right one does. A tie going
    -- the wrong way costs the whole feature, since the true holder then gets pushed off its own weapon.
    -- WGRX has not been written since the weapon's capsules moved to their own bones, so this distance is from the player's
    -- feet and the left hand won whenever it was the lower one: as the support hand, it is then left out of the solve, and
    -- the gun with it. The slot lookup above is the answer; without one, the right hand is.
    if rr then holderSide = 1
    elseif rl then holderSide = 0 end
    return holderSide
end

