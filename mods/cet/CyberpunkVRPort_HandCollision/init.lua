-- A capsule's two model-space endpoints, as six scalars. ox/oy/oz overrides the bone's own position.
local function endpoints(c, ox, oy, oz)
    local px, py, pz, qi, qj, qk, qr = bone(c.index)
    if not px then return nil end
    local bx, by, bz = ox or px, oy or py, oz or pz
    local xx, xy, xz = qrot(qi, qj, qk, qr, 1.0, 0.0, 0.0)
    local yx, yy, yz = qrot(qi, qj, qk, qr, 0.0, 1.0, 0.0)
    local zx, zy, zz = qrot(qi, qj, qk, qr, 0.0, 0.0, 1.0)
    local cx = bx + xx * c.cx + yx * c.cy + zx * c.cz
    local cy = by + xy * c.cx + yy * c.cy + zy * c.cz
    local cz = bz + xz * c.cx + yz * c.cy + zz * c.cz
    local h = c.half
    return cx - xx * h, cy - xy * h, cz - xz * h,
           cx + xx * h, cy + xy * h, cz + xz * h
end

-- Closest points between two segments, all scalars: clamped solve plus the refinement pass that makes it correct
-- when the nearest approach lands on an endpoint.
local function segClosest(pax, pay, paz, pbx, pby, pbz, qax, qay, qaz, qbx, qby, qbz)
    local ux, uy, uz = pbx - pax, pby - pay, pbz - paz
    local vx, vy, vz = qbx - qax, qby - qay, qbz - qaz
    local wx, wy, wz = pax - qax, pay - qay, paz - qaz
    local a = ux * ux + uy * uy + uz * uz
    local b = ux * vx + uy * vy + uz * vz
    local c = vx * vx + vy * vy + vz * vz
    local d = ux * wx + uy * wy + uz * wz
    local e = vx * wx + vy * wy + vz * wz
    local den = a * c - b * b
    local sc = 0.0
    if den > 1e-9 then sc = (b * e - c * d) / den end
    if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    local tc = 0.0
    if c > 1e-9 then
        tc = (e + b * sc) / c
        if tc < 0.0 then tc = 0.0 elseif tc > 1.0 then tc = 1.0 end
    end
    if a > 1e-9 then
        sc = (b * tc - d) / a
        if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    end
    return pax + ux * sc, pay + uy * sc, paz + uz * sc,
           qax + vx * tc, qay + vy * tc, qaz + vz * tc
end

-- Finger capsules: slot named vrp_f_<finger><joint>_<l|r>.
local function fingerSide(slot)
    if slot:sub(1, 6) ~= 'vrp_f_' then return nil end
    local tail = slot:sub(-2)
    if tail == '_l' then return 0 elseif tail == '_r' then return 1 end
    return nil
end

-- Which body capsules may stop the rig hanging off the wrist of `side`. Excluded: everything that wrist's own IK
-- places -- upper arm, forearm, hand -- because a capsule that moves when the wrist is pushed is a feedback loop
-- (cause 1). And every hand and finger capsule of EITHER side, because they all hang off a hand bone that carries
-- a clamp; those come back through ridingSet, placed from a raw target instead.
local OBST, HAND, RIDE = {}, {}, {}
for side = 0, 1 do
    OBST[side] = { n = 0 }
    RIDE[side] = { n = 0 }
    for i = 1, #CAPS do
        local c = CAPS[i]
        c.uid = i
        if c.slot ~= ARM_SLOT[side] and c.slot ~= FORE_SLOT[side]
           and c.slot ~= HAND_SLOT[0] and c.slot ~= HAND_SLOT[1]
           and fingerSide(c.slot) == nil then
            push(OBST[side], c)
        end
        if c.slot == HAND_SLOT[side] then HAND[side] = c end
        if c.slot == HAND_SLOT[side] or fingerSide(c.slot) == side then push(RIDE[side], c) end
    end
end

