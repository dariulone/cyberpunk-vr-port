-- A capsule's two model-space endpoints, as six scalars. ox/oy/oz overrides the bone's own position.
local function endpoints(c, ox, oy, oz)
    local px, py, pz, qi, qj, qk, qr = bone(c.index)
    if not px then return nil end
    local bx, by, bz = ox or px, oy or py, oz or pz
    local xx, xy, xz = qrot(qi, qj, qk, qr, 1.0, 0.0, 0.0)
    local yx, yy, yz = qrot(qi, qj, qk, qr, 0.0, 1.0, 0.0)
    local zx, zy, zz = qrot(qi, qj, qk, qr, 0.0, 0.0, 1.0)
    local cx = bx + xx * c.cx + yx * c.cy + zx * c.cz
    local cy = by + xy * c.cx + yy * c.cy + zy * c.cz
    local cz = bz + xz * c.cx + yz * c.cy + zz * c.cz
    local h = c.half
    return cx - xx * h, cy - xy * h, cz - xz * h,
           cx + xx * h, cy + xy * h, cz + xz * h
end

-- Closest points between two segments, all scalars: clamped solve plus the refinement pass that makes it correct
-- when the nearest approach lands on an endpoint.
local function segClosest(pax, pay, paz, pbx, pby, pbz, qax, qay, qaz, qbx, qby, qbz)
    local ux, uy, uz = pbx - pax, pby - pay, pbz - paz
    local vx, vy, vz = qbx - qax, qby - qay, qbz - qaz
    local wx, wy, wz = pax - qax, pay - qay, paz - qaz
    local a = ux * ux + uy * uy + uz * uz
    local b = ux * vx + uy * vy + uz * vz
    local c = vx * vx + vy * vy + vz * vz
    local d = ux * wx + uy * wy + uz * wz
    local e = vx * wx + vy * wy + vz * wz
    local den = a * c - b * b
    local sc = 0.0
    if den > 1e-9 then sc = (b * e - c * d) / den end
    if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    local tc = 0.0
    if c > 1e-9 then
        tc = (e + b * sc) / c
        if tc < 0.0 then tc = 0.0 elseif tc > 1.0 then tc = 1.0 end
    end
    if a > 1e-9 then
        sc = (b * tc - d) / a
        if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    end
    return pax + ux * sc, pay + uy * sc, paz + uz * sc,
           qax + vx * tc, qay + vy * tc, qaz + vz * tc
end

-- Finger capsules: slot named vrp_f_<finger><joint>_<l|r>.
local function fingerSide(slot)
    if slot:sub(1, 6) ~= 'vrp_f_' then return nil end
    local tail = slot:sub(-2)
    if tail == '_l' then return 0 elseif tail == '_r' then return 1 end
    return nil
end

-- Which body capsules may stop the rig hanging off the wrist of `side`. Excluded: everything that wrist's own IK
-- places -- upper arm, forearm, hand -- because a capsule that moves when the wrist is pushed is a feedback loop
-- (cause 1). And every hand and finger capsule of EITHER side, because they all hang off a hand bone that carries
-- a clamp; those come back through ridingSet, placed from a raw target instead.
local OBST, HAND, RIDE = {}, {}, {}
for side = 0, 1 do
    OBST[side] = { n = 0 }
    RIDE[side] = { n = 0 }
    for i = 1, #CAPS do
        local c = CAPS[i]
        c.uid = i
        if c.slot ~= ARM_SLOT[side] and c.slot ~= FORE_SLOT[side]
           and c.slot ~= HAND_SLOT[0] and c.slot ~= HAND_SLOT[1]
           and fingerSide(c.slot) == nil then
            push(OBST[side], c)
        end
        if c.slot == HAND_SLOT[side] then HAND[side] = c end
        if c.slot == HAND_SLOT[side] or fingerSide(c.slot) == side then push(RIDE[side], c) end
    end
end

-- Contact ids: a body or finger capsule takes its index in CAPS, a gun capsule 100 + its index. The pair
-- (mover, obstacle) tells the roles apart, so the same capsule may appear as both. Integers rather than
-- concatenated strings -- one string per candidate pair was hundreds of allocations a frame.
local GUN_ID = 100

local function buildObstacles(side, out)
    out.n = 0
    local list = OBST[side]
    for i = 1, list.n do
        local c = list[i]
        local ax, ay, az, bx, by, bz = endpoints(c)
        if ax then push(out, cap(c.uid, c.r, ax, ay, az, bx, by, bz, c.slot)) end
    end
    return out
end

-- The palm and every phalanx of `side`, as they would sit with that wrist at x,y,z.
--
-- EXACT rather than an approximation: the finger bones are descendants of the hand bone, so the whole set is
-- rigid with respect to the wrist, and the clamp only ever TRANSLATES the wrist. The set as measured now, moved
-- by (x,y,z) minus the hand bone's position, IS the set with the wrist at x,y,z -- and that subtraction cancels
-- whatever hold was active when the bones were read. So finger geometry stays a function of tracking and of the
-- animated curl, never of last frame's output. The curl matters: a closed fist collides as a fist.
local function ridingSet(side, x, y, z, out)
    local h = HAND[side]
    if not h then return out end
    local hx, hy, hz = bone(h.index)
    if not hx then return out end
    local dx, dy, dz = x - hx, y - hy, z - hz
    local list = RIDE[side]
    for i = 1, list.n do
        local c = list[i]
        local ax, ay, az, bx, by, bz = endpoints(c)
        if ax then
            push(out, cap(c.uid, c.r, ax + dx, ay + dy, az + dz, bx + dx, by + dy, bz + dz, c.slot))
        end
    end
    return out
end

-- The weapon's capsules as they would sit with the holder's wrist at x,y,z. Same exactness argument as above.
local function gunAt(side, x, y, z, out)
    if WGN == 0 then return out end
    local h = HAND[side]
    if not h then return out end
    local hx, hy, hz = bone(h.index)
    if not hx then return out end
    local dx, dy, dz = x - hx, y - hy, z - hz
    for i = 1, WGN do
        local cx, cy, cz = WGX[i] + dx, WGY[i] + dy, WGZ[i] + dz
        local ex, ey, ez = WGDX[i], WGDY[i], WGDZ[i]
        push(out, cap(GUN_ID + i, WCAPS[i].r,
                      cx - ex, cy - ey, cz - ez, cx + ex, cy + ey, cz + ez, WCAPS[i].bone))
    end
    return out
end

-- Translate a RIGID SET of capsules until none of them overlaps any obstacle, and return the translation.
local function resolveRig(side, movers, segs)
    if movers.n == 0 or segs.n == 0 then return 0.0, 0.0, 0.0 end
    local mem = stick[side]
    local tx, ty, tz = 0.0, 0.0, 0.0

    -- COARSE CULL: one sphere test per obstacle against the whole mover set. The pairwise pass below is
    -- movers x obstacles -- 74 x 90 with fingers and a 58-capsule weapon -- and no amount of slack tuning
    -- changes that product; measured, tightening the pairwise slack from 0.15 to 0.05 moved the pair count from
    -- 722 to 806, because the weapon had meanwhile gone from 28 capsules to 58. Culling the obstacles once does
    -- change it. Grown by CULL because this list is built once and must survive the whole hold, measured as far
    -- as 0.166 m.
    NEAR.n = 0
    local cx, cy, cz = 0.0, 0.0, 0.0
    for i = 1, movers.n do
        local m = movers[i]
        cx, cy, cz = cx + m.cx, cy + m.cy, cz + m.cz
    end
    local inv = 1.0 / movers.n
    cx, cy, cz = cx * inv, cy * inv, cz * inv
    local rad = 0.0
    for i = 1, movers.n do
        local m = movers[i]
        local dx, dy, dz = m.cx - cx, m.cy - cy, m.cz - cz
        local d = math.sqrt(dx * dx + dy * dy + dz * dz) + m.e
        if d > rad then rad = d end
    end
    rad = rad + CULL
    for i = 1, segs.n do
        local s = segs[i]
        local dx, dy, dz = s.cx - cx, s.cy - cy, s.cz - cz
        local reach = rad + s.e
        if dx * dx + dy * dy + dz * dz <= reach * reach then push(NEAR, s) end
    end
    if NEAR.n == 0 then return 0.0, 0.0, 0.0 end

    local n = 0
    local function broadphase()
        n = 0
        for mi = 1, movers.n do
            local m = movers[mi]
            local mx, my, mz = m.cx + tx, m.cy + ty, m.cz + tz
            local me, mid = m.e, m.id * 512
            for si = 1, NEAR.n do
                local s = NEAR[si]
                local dx, dy, dz = mx - s.cx, my - s.cy, mz - s.cz
                local reach = me + s.e + BROAD
                if dx * dx + dy * dy + dz * dz <= reach * reach then
                    n = n + 1
                    CD_M[n], CD_S[n], CD_KEY[n] = m, s, mid + s.id
                end
            end
        end
        if n > candMax then candMax = n end
        return n
    end

    if broadphase() == 0 then return 0.0, 0.0, 0.0 end
    local bx, by, bz = 0.0, 0.0, 0.0

    for _ = 1, PASSES do
        -- SEQUENTIAL PROJECTION: each contact is answered in full the moment it is found, and the next one is
        -- evaluated against the already-moved rig. Count-independent, unlike an average -- see cause 4.
        local deepest, dm, ds = 0.0, nil, nil
        for ci = 1, n do
            local m, s, key = CD_M[ci], CD_S[ci], CD_KEY[ci]
            local hx, hy, hz, qx, qy, qz = segClosest(
                m.ax + tx, m.ay + ty, m.az + tz, m.bx + tx, m.by + ty, m.bz + tz,
                s.ax, s.ay, s.az, s.bx, s.by, s.bz)
            local sx, sy, sz = hx - qx, hy - qy, hz - qz
            local dist = math.sqrt(sx * sx + sy * sy + sz * sz)
            local need = m.r + s.r
            local mm = mem[key]
            local limit = need
            if mm then limit = need + RELEASE_MARGIN end
            if dist >= limit then
                if mm then mem[key] = nil end
            else
                local ux, uy, uz
                if dist > 1e-5 then ux, uy, uz = sx / dist, sy / dist, sz / dist
                else ux, uy, uz = 0.0, 0.0, 1.0 end
                if mm then
                    -- keep leaving by the side it first left by; the shortest way out flips once the mover is
                    -- past the axis, and following that flip teleported the hand through the chest
                    if (mm[1] * ux + mm[2] * uy + mm[3] * uz) < 0.0 then
                        ux, uy, uz = mm[1], mm[2], mm[3]
                        dist = -(sx * ux + sy * uy + sz * uz)
                    end
                else
                    mem[key] = { ux, uy, uz }
                end
                local depth = need - dist
                if depth > 0.0 then
                    local step = depth * OMEGA
                    tx, ty, tz = tx + ux * step, ty + uy * step, tz + uz * step
                    if depth > deepest then deepest, dm, ds = depth, m, s end
                end
            end
        end
        if dm then worstM[side], worstS[side] = dm.label, ds.label end
        if deepest <= SETTLED then break end
        local ddx, ddy, ddz = tx - bx, ty - by, tz - bz
        if ddx * ddx + ddy * ddy + ddz * ddz > BROAD * BROAD * 0.25 then
            bx, by, bz = tx, ty, tz
            if broadphase() == 0 then break end
        end
    end
    return tx, ty, tz
end

-- WHICH HAND HOLDS THE WEAPON, latched for the life of that weapon instance. Decided per frame as "nearer wrist"
-- it flipped whenever the free hand came to the grip -- which is where the trigger is -- and each flip swapped
-- which hand was frozen. A weapon does not change hands while equipped.
local HOLDER_DROP = 0.30    -- m: beyond this from the grip, the latched hand plainly is not holding it
local HOLDER_EDGE = 0.05    -- m: the challenger must be this much nearer before the LEFT hand is believed
local holderSide, holderEnt = nil, nil
local dbgDL, dbgDR = -1.0, -1.0

-- WHICH HAND HOLDS THE GUN, asked of the game rather than guessed from geometry.
--
-- The distance test below picks whichever wrist is nearer the grip, and that is wrong exactly when it matters: a
-- hand reaching for the MAGAZINE passes closer to the grip than the hand holding the weapon. The holder then
-- flipped to the free hand -- the gun visibly snapped across to it (the pistol went under the left hand) and the
-- reload's magnet, which always drives the hand that is NOT the holder, started pulling the real gun hand.
--
-- The game already knows the answer: a held weapon is attached to `ItemAttachmentSlots.WeaponRight` or
-- `.WeaponLeft`, and `GetItemInSlot` returns it. Verified live -- the active weapon's entity id came back from
-- WeaponRight and from nowhere else. Cached per weapon, because it cannot change without the weapon changing.
local slotHolder, slotHolderFor = nil, nil
local function holderFromSlot()
    local pl = Game.GetPlayer()
    local w = pl and pl:GetActiveWeapon()
    if not w then slotHolder, slotHolderFor = nil, nil; return nil end
    local okId, wid = pcall(function() return w:GetEntityID().hash end)
    if not okId then return nil end
    if slotHolderFor == wid then return slotHolder end
    local ts = Game.GetTransactionSystem()
    if not ts then return nil end
    local found = nil
    for _, e in ipairs({ { 1, 'AttachmentSlots.WeaponRight' }, { 0, 'AttachmentSlots.WeaponLeft' } }) do
        local ok, it = pcall(function() return ts:GetItemInSlot(pl, TweakDBID.new(e[2])) end)
        if ok and it then
            local ok2, h = pcall(function() return it:GetEntityID().hash end)
            if ok2 and h == wid then found = e[1]; break end
        end
    end
    if found ~= nil then slotHolder, slotHolderFor = found, wid end
    return found
end

local function holderOf(rl, rr)
    -- the game's own answer wins; the geometry below is only for when it has none to give
    local s = holderFromSlot()
    if s ~= nil then
        holderSide, holderEnt = s, slotEnt
        local function d0(v)
            if not v then return -1.0 end
            local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
            return math.sqrt(dx * dx + dy * dy + dz * dz)
        end
        dbgDL, dbgDR = d0(rl), d0(rr)
        return s
    end
    if slotEnt ~= holderEnt then holderSide, holderEnt = nil, slotEnt end
    local function dist(v)
        local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
        return math.sqrt(dx * dx + dy * dy + dz * dz)
    end
    dbgDL = rl and dist(rl) or -1.0
    dbgDR = rr and dist(rr) or -1.0

    if holderSide ~= nil then
        local d = (holderSide == 0) and dbgDL or dbgDR
        if d >= 0.0 and d <= HOLDER_DROP then return holderSide end
        holderSide = nil
    end

    -- Right by default, and the left has to WIN by a margin. Cyberpunk holds a weapon in the right hand; the
    -- left is only ever a support hand, and it can sit as close to the grip as the right one does. A tie going
    -- the wrong way costs the whole feature, since the true holder then gets pushed off its own weapon.
    if rl and rr then
        holderSide = (dbgDL + HOLDER_EDGE < dbgDR) and 0 or 1
    elseif rr then holderSide = 1
    elseif rl then holderSide = 0 end
    return holderSide
end

local logAcc = 0.0
local PX, PY, PZ = {}, {}, {}      -- the resolved wrist per side, reused
local RAW = {}

-- STAGE TRACER: which point the LAST frame reached and with what inputs, printed once a second from the TOP of
-- onUpdate (before any early return can silence it). Exists because the grip died with zero log output twice, and
-- each time the silent early-out cost a debugging round to even locate.
local dbgStage, dbgAcc, dbgNote = 'never-ran', 0.0, ''
-- dbgOn(), sampled by the tracer's own once-a-second tick: the notes are formatted only while somebody reads them.
local traceOn = false

-- The collision-off release, without a fresh Vector4 and closure per hand per frame.
local ZERO4 = nil
local function releaseHand(side)
    if not ZERO4 then ZERO4 = Vector4.new(0, 0, 0, 0) end
    VRHandStopModel(side, false, ZERO4)
end

registerForEvent('onUpdate', function(dt)
    dbgAcc = dbgAcc + (dt or 0.016)
    if dbgAcc >= 1.0 then
        dbgAcc = 0.0
        traceOn = dbgOn()
        if traceOn then
            pcall(function() spdlog.info(string.format('[Tick] stage=%s %s ownHand=%s collOn=%s',
                dbgStage, dbgNote,
                (type(GetVRSharedSlot) == 'function') and tostring(GetVRSharedSlot(162)) or '?',
                tostring(COLL_ON))) end)
        end
    end
    local t0 = (os and os.clock) and os.clock() or nil
    dbgStage, dbgNote = 'natives', ''
    if type(VRHandRawModel) ~= 'function' or type(VRHandStopModel) ~= 'function' then return end
    if type(VRBoneModelPos) ~= 'function' or type(VRBoneModelRot) ~= 'function' then return end
    if type(SetVRDiagCapture) ~= 'function' then return end
    ensureCapture()
    ensureDeadband()
    -- The census is NOT started any more: identification is by bone name in the hook, and the census recorded
    -- every skeleton in the world on the hot path for nothing.
    if not censusStarted then censusStarted, censusAt = true, 0.0 end

    gen = gen + 1
    poolN = 0

    local rl, rr = VRHandRawModel(0), VRHandRawModel(1)
    dbgStage = 'hands'
    if traceOn then dbgNote = string.format('Lw=%.1f Rw=%.1f', rl and rl.w or -1, rr and rr.w or -1) end
    if rl and rl.w < 0.5 then rl = nil end
    if rr and rr.w < 0.5 then rr = nil end
    if not rl and not rr then return end
    RAW[0], RAW[1] = rl, rr
    if rl then PX[0], PY[0], PZ[0] = rl.x, rl.y, rl.z end
    if rr then PX[1], PY[1], PZ[1] = rr.x, rr.y, rr.z end

    local holder = nil
    -- With the collision off the slots, and the holder, only feed the tracer's note.
    local haveGun = readWeapon(COLL_ON) > 0
    if type(VRPoseCensus) == 'function' then VRPoseCensus(-4, haveGun and 1 or 0) end
    if haveGun and (COLL_ON or traceOn) then
        holder = holderOf(rl, rr)
        if holder ~= nil and (not RAW[holder] or not HAND[holder]) then holder = nil end
    end

    -- COLLISION OFF (dev): release both hands so nothing clamps them, run only the physical reload, and stop.
    if not COLL_ON then
        dbgStage = 'colloff'
        if traceOn then
            dbgNote = string.format('gun=%s holder=%s slotComp=%s', tostring(haveGun), tostring(holder), tostring(slotComp ~= nil))
        end
        -- ...EXCEPT THE WRIST THE RELOAD HOLDS, and that exception is what the split cost here. While the
        -- reload lived in this file the release was safe by construction: it ran, and the reload's frame
        -- re-took its wrist two statements later in this same callback. Two mods have no guaranteed
        -- callback order, so a release can land AFTER the hold and cancel it -- which is a magnet that
        -- simply does not hold. Same rule the solve path below has always used for the owned wrist.
        local ownRel = nil
        if type(GetVRSharedSlot) == 'function' then
            local v = GetVRSharedSlot(162)
            if v == 0.0 or v == 1.0 then ownRel = math.floor(v) end
        end
        if ownRel ~= 0 then pcall(releaseHand, 0) end
        if ownRel ~= 1 then pcall(releaseHand, 1) end
        bodyCapsulesForVehicle(os.clock())
        return
    end

    
-- THE HAND THE RELOAD OWNS. While it glues a wrist to a weapon part (the slide's grip, the magazine's magnet) that
    -- wrist has exactly one writer -- the reload's -- and this solve must neither push it nor publish it. Two writers
    -- on one wrist is a shake, not a compromise: this module publishes a push-OUT of the gun every frame and the
    -- reload then writes its own hold over it, so the pin is dropped and re-taken frame after frame. And leaving the
    -- owned hand out of the solve is the same rule that killed the first shake -- nothing an IK solve places may be an
    -- obstacle for it -- since the reload deliberately holds that hand against the very part this would push it off.
    -- The flag is one frame old (the reload runs in its own mod, after this one): right, because ownership
    -- changes at the speed of a hand.
    --
    -- THROUGH SHARED SLOT [162], which is what the split cost. Two CET mods are two sandboxes and cannot see each
    -- other's tables, so the reload publishes the wrist it owns (SetVRReloadOwnedHand) and this reads it. -1 means
    -- nobody owns a wrist -- including when the reload mod is not installed at all, which is the point: this module
    -- now runs without it.
    local ownHand = nil
    if type(GetVRSharedSlot) == 'function' then
        local v = GetVRSharedSlot(162)
        if v == 0.0 or v == 1.0 then ownHand = math.floor(v) end
    end

    if holder ~= nil then
        -- 1. THE HOLDER: its hand, its fingers and the whole gun, against the body. Placed from the RAW wrist, so
        --    this step depends on nothing but tracking, which is what lets the gun be pushed at all without the
        --    shake coming back.
        local h = RAW[holder]
        LA.n = 0
        ridingSet(holder, h.x, h.y, h.z, LA)
        gunAt(holder, h.x, h.y, h.z, LA)
        local dx, dy, dz = resolveRig(holder, LA, buildObstacles(holder, LB))
        PX[holder], PY[holder], PZ[holder] = h.x + dx, h.y + dy, h.z + dz

        -- 2. THE FREE HAND: against the body, against the gun where step 1 just put it, and against the holder's
        --    hand and fingers. One sequential solve over all three, so the answer satisfies them together.
        local free = 1 - holder
        local f = RAW[free]
        if f and HAND[free] and free ~= ownHand then
            buildObstacles(free, LB)
            gunAt(holder, PX[holder], PY[holder], PZ[holder], LB)
            ridingSet(holder, PX[holder], PY[holder], PZ[holder], LB)
            LA.n = 0
            ridingSet(free, f.x, f.y, f.z, LA)
            local ex, ey, ez = resolveRig(free, LA, LB)
            PX[free], PY[free], PZ[free] = f.x + ex, f.y + ey, f.z + ez
        elseif f then
            PX[free], PY[free], PZ[free] = f.x, f.y, f.z    -- the reload owns it: leave it exactly where tracking says
        end
    else
        -- 3. NO WEAPON: each hand against the body, then hand against hand.
        for side = 0, 1 do
            local r0 = RAW[side]
            if r0 and HAND[side] then
                LA.n = 0
                ridingSet(side, r0.x, r0.y, r0.z, LA)
                local dx, dy, dz = resolveRig(side, LA, buildObstacles(side, LB))
                PX[side], PY[side], PZ[side] = r0.x + dx, r0.y + dy, r0.z + dz
            end
        end
        -- Fingers and all: solve the left set against the right set held still, then split the answer between
        -- them. Both are placed from positions that are pure functions of tracking, so this cannot ring, and half
        -- each is what two equal masses meeting would do -- pushing only one would make the same gesture behave
        -- differently depending on which hand you moved.
        if rl and rr and HAND[0] and HAND[1] then
            LA.n = 0; LB.n = 0
            ridingSet(0, PX[0], PY[0], PZ[0], LA)
            ridingSet(1, PX[1], PY[1], PZ[1], LB)
            local dx, dy, dz = resolveRig(0, LA, LB)
            PX[0], PY[0], PZ[0] = PX[0] + dx * 0.5, PY[0] + dy * 0.5, PZ[0] + dz * 0.5
            PX[1], PY[1], PZ[1] = PX[1] - dx * 0.5, PY[1] - dy * 0.5, PZ[1] - dz * 0.5
        end
    end

    -- Publishing, with a limit and a soft release. Past MAX_HOLD the drawn hand is so far from the real one that
    -- keeping it there is worse than letting go -- but letting go in one frame is the snap that reads as a
    -- teleport, so the hold is faded out over RELEASE seconds instead.
    local function send(side)
        if ownHand == side then
            smooth[side], lastStep[side] = nil, nil    -- no accumulated hold to carry back when we take it again
            return 0.0
        end
        local r0 = RAW[side]
        if not r0 then
            VRHandStopModel(side, false, Vector4.new(0, 0, 0, 0))
            smooth[side], lastStep[side] = nil, nil
            return 0.0
        end
        local ox, oy, oz = PX[side] - r0.x, PY[side] - r0.y, PZ[side] - r0.z
        local prev = smooth[side]
        if prev then
            local sx, sy, sz = ox - prev[1], oy - prev[2], oz - prev[3]
            -- SIGN-FLIP DAMPER. A hold whose change reverses direction from one frame to the next is ringing,
            -- not motion, so only part of it is taken; a steady push never reverses and pays nothing.
            local ls = lastStep[side]
            if ls and (sx * ls[1] + sy * ls[2] + sz * ls[3]) < 0.0 then
                sx, sy, sz = sx * 0.35, sy * 0.35, sz * 0.35
                flips[side] = flips[side] + 1
            end
            ls = ls or {}
            ls[1], ls[2], ls[3] = sx, sy, sz
            lastStep[side] = ls
            local k = 1.0 - math.exp(-(dt or 0.016) / SMOOTH_TAU)
            ox, oy, oz = prev[1] + sx * k, prev[2] + sy * k, prev[3] + sz * k
        else
            lastStep[side] = nil
        end
        prev = prev or {}
        prev[1], prev[2], prev[3] = ox, oy, oz
        smooth[side] = prev

        local off = math.sqrt(ox * ox + oy * oy + oz * oz)
        if off > MAX_HOLD then fade[side] = RELEASE end
        local kf = 1.0
        if fade[side] > 0.0 then
            fade[side] = fade[side] - (dt or 0.016)
            kf = math.max(0.0, fade[side]) / RELEASE
            off = off * kf
        end
        VRHandStopModel(side, off > DEAD,
            Vector4.new(r0.x + ox * kf, r0.y + oy * kf, r0.z + oz * kf, 1.0))
        return off
    end

    local offL, offR = send(0), send(1)

    -- Body capsules are switched at the component level; no physical-body handles
    -- survive across a registration or player-state change.
    bodyCapsulesForVehicle(os.clock())

    if t0 then
        local ms = (os.clock() - t0) * 1000.0
        msAcc, msN = msAcc + ms, msN + 1
        if ms > msMax then msMax = ms end
    end

    logAcc = logAcc + (dt or 0.016)
    if logAcc >= 1.0 and dbgOn() then
        logAcc = 0.0
        pcall(function()
            spdlog.info(string.format(
                "[HandColl] holder=%s (grip L=%.3f R=%.3f) caps=%d w=%s slots=%s gun=%d miss=%d pairs<=%d pool=%d solve %.2f/%.2f ms | held L=%.3f R=%.3f"
                .. " | stopped by L=%s>%s R=%s>%s | reversals/s L=%d R=%d",
                tostring(holder), dbgDL, dbgDR, #CAPS,
                lastW and 'yes' or 'no', slotComp and 'yes' or 'no', WGN, wMiss, candMax, poolN,
                (msN > 0) and (msAcc / msN) or -1.0, msMax, offL, offR,
                tostring(worstM[0]), tostring(worstS[0]), tostring(worstM[1]), tostring(worstS[1]),
                flips[0], flips[1]))
        end)
        -- THE RELOAD GATE. Parts whose local translation is moving are the ones the reload animation drives, and
        -- those are exactly the ones a physical reload has to write.
        -- THE CENSUS, reported so the weapon's rigs can be picked out by eye once: entries that only exist
        -- while a gun is in hand, with a small hit count each (four rigs, a few passes a tick).
        if type(VRPoseCensus) == 'function' and censusAt then
            pcall(function()
                -- The two rigs, nominated by the (bones, tracks) pair the pose descriptor carries and
                -- checked against the rig assets: 16 bones and 0 tracks for the frame, 5 and 2 for the magazine.
                local rows = {}
                for w = 0, 1 do
                    rows[#rows + 1] = string.format('%s seen=%d bones=%d tracks=%d buf=%08X%08X',
                        (w == 0) and 'mag' or 'frame',
                        VRRigStatus(0 + w), VRRigStatus(2 + w), VRRigStatus(4 + w),
                        VRRigStatus(8 + w), VRRigStatus(6 + w))
                end
                spdlog.info(string.format("[Rig] weapon=%s | %s",
                    (WGN > 0) and 'yes' or 'no', table.concat(rows, ' | ')))
            end)
        end
        flips[0], flips[1] = 0, 0
        worstM[0], worstS[0], worstM[1], worstS[1] = '-', '-', '-', '-'
        candMax = 0
        msAcc, msMax, msN = 0.0, 0.0, 0
    end
end)

