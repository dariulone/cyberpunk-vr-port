    if outer then
        if outer:find('coat', 1, true) or outer:find('jacket', 1, true) or outer:find('bomber', 1, true) or outer:find('puffer', 1, true) then pad = 0.025
        elseif outer:find('vest', 1, true) then pad = 0.012
