local NFX, NFY = {}, {}            -- which way each faces, world x y
-- m: a joint stays put until it has moved this far (a breath), then follows at that distance. At 2 cm the capsules sat
-- up to 2 cm off the bones of someone standing still, and a hand that took hold of an arm was that far off it.
local NPC_SWAY = 0.006
-- A PERSON'S PART TAKEN HOLD OF (Natives/PhysHands: the grip closed on one of their capsules) is pulled a little toward
-- the controller: the person is moved along the floor by at most NPC_TUG_STEP every NPC_TUG_EVERY s and NPC_TUG_MOST in
