-- A PERSON TAKEN (src/Anim/NpcArmGrip.cpp), by what is nearest the palm: an arm, a leg, the head, the chest. What is held stays where the grip has it, as it stood from the wrist when it closed, and the rest of them goes on. Past
-- what that part can reach, however it bends, the grip gives.
K.npcGripStart = function(side, bx, by, bz, ii, ij, ik, ir)
    if type(VRNpcGrip) ~= 'function' then return false end
    -- the real hand: the drawn one stops at the person's capsules, and from here on lies on them
    local px, py, pz, qi, qj, qk, qr = handReal(side, bx, by, bz, ii, ij, ik, ir)
    if not px then return false end
    local sx, sy, sz = qrot(qi, qj, qk, qr, palmSkin(side))
    local ax, ay, az = px + sx, py + sy, pz + sz
    local function slotAt(comp, slot)
        local o, found, tr = pcall(slotTransform, comp, CName.new(slot))
        if not o or not found or not tr then return nil end
        local okP, wp = pcall(slotPosition, tr)
        return okP and wp or nil
    end
    local best, bestAt, bestPart, bestD, bestSpot = nil, nil, nil, 1.0, nil
    for i = 1, #npcList do
        local rec = NPC_BODY.at[i]
        if rec and rec.comp then
            for _, P in ipairs(K.NPC_PARTS) do
                for _, slot in ipairs(P.slots) do
                    local wp = slotAt(rec.comp, slot)
                    if wp then
                        local d = math.sqrt((wp.x - ax) * (wp.x - ax) + (wp.y - ay) * (wp.y - ay) + (wp.z - az) * (wp.z - az)) / P.reach
                        if d < bestD then best, bestAt, bestPart, bestD, bestSpot = npcList[i], rec, P, d, wp end
                    end
                end
            end
        end
    end
    if not best then return false end
    -- where that part is now, from this wrist's frame: kept as it is
    local wp = slotAt(bestAt.comp, bestPart.ref)
    local okQ, q = pcall(worldRot, best)
    if not wp or not okQ or not q then return false end
    local ox, oy, oz = qrot(-qi, -qj, -qk, qr, wp.x - px, wp.y - py, wp.z - pz)
    local mi, mj, mk, mr = qmul(-q.i, -q.j, -q.k, q.r, qi, qj, qk, qr)
    K.NPC_GRIP[side] = { npc = best, part = bestPart.part, ox = ox, oy = oy, oz = oz, mi = mi, mj = mj, mk = mk, mr = mr, torn = 0.0, age = 0.0 }
    -- THE HAND LIES ON THEM. It closed up to a quarter of a metre off, and what is held stays as it stood from the hand: so it is the drawn hand that goes the rest of the way, to the skin of what it took.
    do
        local cx, cy, cz = bestSpot.x, bestSpot.y, bestSpot.z
        cz = cz + math.max(-(bestPart.down or 0.0), math.min(bestPart.up or 0.0, az - cz))
        local dx, dy, dz = cx - ax, cy - ay, cz - az
        local d = math.sqrt(dx * dx + dy * dy + dz * dz)
        local gap = math.min(d - bestPart.skin, 0.3)
        K.NPC_GRIP[side].gap = gap
        if gap > 0.0 and d > 1e-3 then
            local wx, wy, wz = dx / d * gap, dy / d * gap, dz / d * gap
            local G = K.NPC_GRIP[side]
            -- kept in the person's frame for what follows the palm's place, in the hand's for what turns with it
            if bestPart.part >= 4 then G.dwx, G.dwy, G.dwz = qrot(-q.i, -q.j, -q.k, q.r, wx, wy, wz)
            else G.dwx, G.dwy, G.dwz = qrot(-qi, -qj, -qk, qr, wx, wy, wz) end
        end
    end
    local said = string.format('[HandColl] a person taken by the %s, %.2f m from the palm', bestPart.name, bestD * bestPart.reach)
    pcall(function() spdlog.info(said) end)
    K.pulse(side)
    return true
end
-- A PERSON'S PART HELD BY A PHYSICS HAND (Natives/PhysHands: the grip closed on one of their capsules, VRPhysHandsGrab names
-- it) is pulled by that part's own bones (src/Anim/NpcArmGrip.cpp): an arm by its hand, a leg by its foot, the head, the
-- chest, kept where they stood from the controller as the grip closed. The physics hand stays on the part, so it follows
-- what it pulls; past what the part can reach the controller draws away from it, and the physics hand lets go.
-- THE CONTROLLER ALONE, world space: its tracked place and turn (VRHandRawRot), nothing of the drawn hand. The drawn hand is
-- the physics hand, kept on the part it holds: a part pulled after the drawn hand's turn turned the hand with it, and the
-- two turned each other round (a held hand spun, 2026-11-10).
K.handTracked = function(side, bx, by, bz, ii, ij, ik, ir)
    local r = RAW[side]
    if not r or type(VRHandRawRot) ~= 'function' then return nil end
    local okQ, q = pcall(VRHandRawRot, side)
    if not okQ or not q then return nil end
    local px, py, pz = qrot(-ii, -ij, -ik, ir, r.x, r.y, r.z)
    local qi, qj, qk, qr = qmul(-ii, -ij, -ik, ir, q.i, q.j, q.k, q.r)
    return px + bx, py + by, pz + bz, qi, qj, qk, qr
end
K.npcGrabFollow = function(side, dt, bx, by, bz, ii, ij, ik, ir)
    if type(VRPhysHandsGrab) ~= 'function' or type(VRNpcGrip) ~= 'function' then return end
    local okG, g = pcall(VRPhysHandsGrab, side)
    local owner = (okG and g and g.w > 0.5) and math.floor(g.w + 0.5) or 0
    local B = NPC_BODY
    B.heldRec = B.heldRec or {}
    local G = K.NPC_GRIP[side]
    if G and (not G.phys or G.owner ~= owner) then
        if type(VRPhysHandsGrabStyle) == 'function' then pcall(VRPhysHandsGrabStyle, side, 0, 0) end
        pcall(VRNpcGrip, G.npc, side, G.part, Vector4.new(0.0, 0.0, 0.0, 0.0), Vector4.new(0.0, 0.0, 0.0, 1.0))
        if G.rec then G.rec.held = nil end
        B.heldRec[side] = nil
        K.NPC_GRIP[side] = nil
        G = nil
    end
    if owner == 0 then return end
    if not G then
        local rec = npcFind(math.floor(owner / 32))
        local kind = rec and rec.kinds and rec.kinds[owner % 32 + 1]
        local P = kind and K.NPC_PARTS[kind + 1]
        if not P or not rec.e or not rec.comp then return end
        local px, py, pz, qi, qj, qk, qr = K.handTracked(side, bx, by, bz, ii, ij, ik, ir)
        if not px then return end
        local o, found, tr = pcall(slotTransform, rec.comp, CName.new(P.ref))
        if not o or not found or not tr then return end
        local okP, wp = pcall(slotPosition, tr)
        local okQ, q = pcall(worldRot, rec.e)
        if not okP or not wp or not okQ or not q then return end
        local ox, oy, oz = qrot(-qi, -qj, -qk, qr, wp.x - px, wp.y - py, wp.z - pz)
        local mi, mj, mk, mr = qmul(-q.i, -q.j, -q.k, q.r, qi, qj, qk, qr)
        K.NPC_GRIP[side] = { npc = rec.e, part = P.part, ox = ox, oy = oy, oz = oz, mi = mi, mj = mj, mk = mk, mr = mr, torn = 0.0,
                             age = 0.0, phys = true, owner = owner, rec = rec }
        rec.held = true
        B.heldRec[side] = rec
        -- THE GRASP: the part's own; the hips by their side (the hand out past their width: round it) or by the buttocks or the
        -- belly (the palm), a thigh round it but by the buttock (behind it, at its top: the palm). The person's frame: X to
        -- their right, Y ahead, Z up from their feet.
        local style = rec.grips and rec.grips[owner % 32 + 1] or 0
        if style == 6 or style == 7 then
            local okE, en = pcall(worldPos, rec.e)
            if okE and en then
                local lx, ly, lz = qrot(-q.i, -q.j, -q.k, q.r, px - en.x, py - en.y, pz - en.z)
                if style == 6 then style = math.abs(lx) > 0.12 and 1 or 4
                else style = (ly < -0.02 and lz > 0.62) and 4 or 1 end
            else
                style = style == 6 and 4 or 1
            end
        end
        K.NPC_GRIP[side].style = style
        if style > 0 and type(VRPhysHandsGrabStyle) == 'function' then pcall(VRPhysHandsGrabStyle, side, owner, style) end
        local said = string.format('[HandColl] a physics hand holds a person by the %s (capsule %d): pulled by its bones, the fingers %s',
                                   P.name, owner % 32, ({ 'round it like a can', 'round it, wide', 'on it gently', 'the palm on it' })[style] or 'as they lie')
        pcall(function() spdlog.info(said) end)
        return
    end
    K.npcGripTick(side, true, dt, bx, by, bz, ii, ij, ik, ir)
end
K.npcGripTick = function(side, grip, dt, bx, by, bz, ii, ij, ik, ir)
    local G = K.NPC_GRIP[side]
    if not G then return end
    local px, py, pz, qi, qj, qk, qr = (G.phys and K.handTracked or handReal)(side, bx, by, bz, ii, ij, ik, ir)
    local okE, e = pcall(worldPos, G.npc)
    local okQ, q = pcall(worldRot, G.npc)
    local ok = grip and px and okE and e and okQ and q
    local mx, my, mz = 0.0, 0.0, 0.0
    local ti, tj, tk, tr = 0.0, 0.0, 0.0, 1.0
    if ok then
        -- A HEAD OR A CHEST GOES WHERE THE PALM GOES. A point 20 cm off the wrist, turned with it, swung round on a neck half as long: the head went round twice as fast as the hand. The turn itself is passed on below.
        local wx, wy, wz
        if G.part >= 4 then wx, wy, wz = qrot(qi, qj, qk, qr, palmSkin(side))
        else wx, wy, wz = qrot(qi, qj, qk, qr, G.ox, G.oy, G.oz) end
        mx, my, mz = qrot(-q.i, -q.j, -q.k, q.r, px + wx - e.x, py + wy - e.y, pz + wz - e.z)
        ok = mx * mx + my * my + (mz - 1.3) * (mz - 1.3) < K.NPC_REACH * K.NPC_REACH
        local ni, nj, nk, nr = qmul(-q.i, -q.j, -q.k, q.r, qi, qj, qk, qr)
        ti, tj, tk, tr = qmul(ni, nj, nk, nr, -G.mi, -G.mj, -G.mk, G.mr)
    end
    local miss = 0.0
    if ok then
        local okS, answer = pcall(VRNpcGrip, G.npc, side, G.part, Vector4.new(mx, my, mz, 1.0), Vector4.new(ti, tj, tk, tr))
        if not okS or not answer or answer < 0.0 then
            K.NPC_GRIP[side] = nil
            sayOnce('a person could not be held: ' .. tostring(answer))
            return
        end
        miss = answer
        -- solved once on a pose, a neck gives some 11 cm, no longer four times that: a head or a chest is let go of a little further off
        G.torn = miss > (G.part >= 4 and 0.25 or K.NPC_TEAR) and G.torn + dt or 0.0
        -- a physics hand's hold lets go by itself (the controller drawn grab_release from it): torn here as well, it was let
        -- go of and taken again every tenth of a second while the part could not reach
        ok = G.phys or G.torn < K.NPC_TEAR_FOR
        if not ok then K.pulse(side) end
    end
    if not ok then
        pcall(VRNpcGrip, G.npc, side, G.part, Vector4.new(0.0, 0.0, 0.0, 0.0), Vector4.new(0.0, 0.0, 0.0, 1.0))
        K.NPC_GRIP[side] = nil
    elseif G.dwx then
        G.age = G.age + dt
        local k = math.min(1.0, G.age / K.HAND_TO_IT_TIME)
        local wx, wy, wz
        if G.part >= 4 then wx, wy, wz = qrot(q.i, q.j, q.k, q.r, G.dwx, G.dwy, G.dwz)
        else wx, wy, wz = qrot(qi, qj, qk, qr, G.dwx, G.dwy, G.dwz) end
        G.dx, G.dy, G.dz = qrot(ii, ij, ik, ir, wx * k, wy * k, wz * k)
        -- did it get there? For the test.
        if not G.said and G.age > 0.5 then
            G.said = true
            local dw = math.sqrt(wx * wx + wy * wy + wz * wz)
            local r = RAW[side]
            local h = HAND[side]
            local hx, hy, hz
            if h then hx, hy, hz = bone(h.index) end
            local real = r and hx and math.sqrt((hx - r.x) * (hx - r.x) + (hy - r.y) * (hy - r.y) + (hz - r.z) * (hz - r.z)) or -1.0
            local said = string.format('[HandColl] the hand on a person: to go %.3f m, asked %.3f m, the drawn wrist is %.3f m from the real one', G.gap or 0.0, dw, real)
            pcall(function() spdlog.info(said) end)
        end
    end
end
K.npcTick = function(side, edge, bx, by, bz, ii, ij, ik, ir)
    local now = os.clock()
    -- WITH THE PHYSICS HANDS the hands rest on people, take hold of them and stroke their hair: a bump each time had a
    -- passer-by turn on V within a few touches. Only a blow is one: the hand at K.NPC_BLOW or faster, the grip's press no.
    if K.PHYS then
        local v = HF[side]
        if edge or v[1] * v[1] + v[2] * v[2] + v[3] * v[3] < K.NPC_BLOW * K.NPC_BLOW then return end
        if now < (K.NPC_NEXT or 0.0) then return end
    elseif not edge then
        local v = HF[side]
        if v[1] * v[1] + v[2] * v[2] + v[3] * v[3] < K.NPC_MOVING * K.NPC_MOVING then return end
        if now < (K.NPC_NEXT or 0.0) then return end
    end
    local n = K.npcNear(side, bx, by, bz, ii, ij, ik, ir)
    if not n then return end
    -- The Animated ragdoll was tried: the bodies appear, and the person goes on as they were (test 2026-11-04). So a grip is a touch too, for now.
    K.NPC_NEXT = now + K.NPC_EVERY
    local pl = Game.GetPlayer()
    local ok, err = pcall(function() pl:GetStimBroadcasterComponent():SendDrirectStimuliToTarget(pl, gamedataStimType.Bump, n) end)
    K.NPC_SAID = (K.NPC_SAID or 0) + 1
    if K.NPC_SAID <= 6 then pcall(function() spdlog.info('[HandColl] a person touched: bump stimulus, ' .. (ok and 'sent' or tostring(err))) end) end
    K.pulse(side)
end

-- THE BODY AGAINST THE HAND, drawn in the world while the debug view is on (or drawCarried(true) from GetMod) and Debug Draw is
-- installed. Orange: the body as the physics system has it, which is what hits things. Green: where the hand has it. With the
-- picture on (xr_carry_picture) the eye sees the thing at the green box, with it off at the orange one. White: the picture as
-- drawn, only where it is not on the hand (short of a wall, blending in or out). A line joins the body to the hand. The channel
-- is cleared before each set, so the second call of a frame replaces the first rather than doubling it.
K.DRAW_HALF = 0.5           -- GetDimensions gives the whole box; Debug Draw takes half extents
K.DRAW_LINE = 0.004         -- m
K.drawBox = function(x, y, z, i, j, k, r, off, half, color, ch)
    local t = Transform.new()
    local ox, oy, oz = qrot(i, j, k, r, off[1], off[2], off[3])
    t.position = Vector4.new(x + ox, y + oy, z + oz, 1.0)
    t.orientation = Quaternion.new(i, j, k, r)
    DebugDraw.OrientedBox(t, half, color, 0.0, true, ch, K.DRAW_LINE)
    return x + ox, y + oy, z + oz
end
