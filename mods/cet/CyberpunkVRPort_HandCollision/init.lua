-- their AI (an AITeleportCommand): the teleportation facility's own Teleport left a living NPC where they stood.
-- Off: a held arm already follows the hand on its own (the NPC's limbs are physical and the hand pulls them), and an AI
-- command twenty times a second is more of the game's machinery than a tug is worth; a job crashed on a game object
-- being remade under it after a session of them (2026-11-10, not shown to be this).
local NPC_TUG, NPC_TUG_FROM, NPC_TUG_STEP, NPC_TUG_EVERY, NPC_TUG_MOST = false, 0.07, 0.01, 0.05, 0.10
local NPC_BODY = { recs = {}, at = {}, turn = 0, seen = false, nextUid = 1,
    slots = { 'Head', 'Chest', 'Hips', 'LeftArm', 'RightArm', 'LeftForeArm', 'RightForeArm', 'LeftHand', 'RightHand',
              'LegLeft', 'LegRight', 'LeftFoot', 'RightFoot', 'BroadPhase' },
    -- joint, joint, radius, and how far the capsule's end sits above the joint
    -- The ragdoll's radii, wider on the trunk and legs: clothes and flesh stand further off a bone than its ragdoll does.
    bones = { { 3, 2, 0.145 }, { 2, 1, 0.060 }, { 1, 1, 0.095, 0.09 }, { 2, 4, 0.070 }, { 2, 5, 0.070 },
              { 4, 6, 0.060 }, { 5, 7, 0.060 }, { 6, 8, 0.050 }, { 7, 9, 0.050 },
              { 3, 10, 0.105 }, { 3, 11, 0.105 }, { 10, 12, 0.080 }, { 11, 13, 0.080 } },
}

local function npcAlive(e)
    if not e:IsA('NPCPuppet') or not ScriptedPuppet.IsAlive(e) then return false end
    -- Mirror actors occupy the player's location or are holographic reflections, not touchable people.
    -- Publishing their capsules as NPCs lets the player's hands push their own visual double.
    local record = TDBID.ToStringDEBUG(e:GetRecordID())
    return record ~= 'Character.q110_tpp_male_v' and record ~= 'Character.q110_tpp_female_v'
        and record ~= 'Character.johnny_mirror'
end

local function npcRefresh()
    local list = {}
    pcall(function()
        local pl = Game.GetPlayer()
        local q = TSQ_ALL()
        q.maxDistance = NPC_RANGE
        q.testedSet = TargetingSet.Complete
        q.ignoreInstigator = true
        local ok, parts = Game.GetTargetingSystem():GetTargetParts(pl, q)
        if not ok or not parts then return end
        local seen = {}
        for _, part in ipairs(parts) do
            local c = part:GetComponent()
            local e = c and c:GetEntity()
            if e then
                local id = tostring(e:GetEntityID().hash)
                if not seen[id] then
                    seen[id] = true
                    local okA, alive = pcall(npcAlive, e)
                    if okA and alive and #list < NPC_MAX then list[#list + 1] = e end
                end
            end
        end
    end)
    npcList = list
    -- what is known of each person is kept by who they are, since the list is rebuilt four times a second
    local b, recs = NPC_BODY, {}
    for i = 1, #list do
        local id = tostring(list[i]:GetEntityID().hash)
        if not b.recs[id] then
            b.recs[id] = { n = 0, uid = b.nextUid }
            b.nextUid = b.nextUid % 500000 + 1
        end
        recs[id] = b.recs[id]
        recs[id].e = list[i]
        b.at[i] = recs[id]
    end
    for i = #list + 1, NPC_MAX do b.at[i] = nil end
    b.recs = recs
end

-- The slots of one person, world space.
local function worldFwd(e) return e:GetWorldForward() end
local function bodyType(e) return NameToString(e:GetBodyType()) end
local function npcReadBones(rec)
    local b = NPC_BODY
    -- where the person stood and faced as the slots were read: the slots are carried by the person's step and turn
    -- from here until they are read again (npcCarry)
    local okE, ep = pcall(worldPos, rec.e)
    local okF, fw = pcall(worldFwd, rec.e)
    if okE and ep then rec.ex, rec.ey, rec.ez = ep.x, ep.y, ep.z else rec.ex = nil end
    if okF and fw then rec.efx, rec.efy = fw.x, fw.y else rec.efx = nil end
    if rec.kind == nil then
        local okB, k = pcall(bodyType, rec.e)
        rec.kind = okB and k or ''
    end
    rec.q = rec.q or {}
    if not rec.comp then
        if rec.noComp then return end
        local cs = Game.VREntityComponents(rec.e)
        for i = 1, #cs do
            if NameToString(cs[i]:GetName()) == 'Item_Attachment_Slot' then rec.comp = cs[i] break end
        end
        if not rec.comp then rec.noComp = true return end
    end
    if not b.names then
        b.names = {}
        for i = 1, #b.slots do b.names[i] = CName.new(b.slots[i]) end
    end
    local n = 0
    for i = 1, #b.slots do
        local o, found, tr = pcall(slotTransform, rec.comp, b.names[i])
        local okP, wp = false, nil
        if o and found and tr then okP, wp = pcall(slotPosition, tr) end
        if okP and wp then
            n = n + 1
            local q, m = tr.Orientation, i * 4
            rec.q[m - 3], rec.q[m - 2], rec.q[m - 1], rec.q[m] = q.i, q.j, q.k, q.r
            -- A joint stays put until it has moved more than the sway of someone standing still, and then follows at that distance. A
            -- hand resting on a head was carried about by every breath, and round the curve of the capsule besides.
            -- (none kept back for someone a hand holds: what is held is pulled, and the hand on it follows it exactly)
            local ox, oy, oz = rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3]
            local sway = rec.held and 0.0 or NPC_SWAY
            if ox then
                local dx, dy, dz = wp.x - ox, wp.y - oy, wp.z - oz
                local d = math.sqrt(dx * dx + dy * dy + dz * dz)
                if d > sway then
                    local k = 1.0 - sway / d
                    rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3] = ox + dx * k, oy + dy * k, oz + dz * k
                end
            else
                rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3] = wp.x, wp.y, wp.z
            end
        else
            rec[i * 3 - 2] = false
        end
    end
    rec.n = n
    if not b.seen and n > 0 then
        b.seen = true
        pcall(function() spdlog.info(string.format('[HandColl] npc bones: %d of %d slots answer', n, #b.slots)) end)
    end
end

-- Where they stand this frame, in model space.
local function npcPlace(dt)
    npcClock = npcClock + dt
    if npcClock - npcAt >= NPC_EVERY then
        npcAt = npcClock
        npcRefresh()
    end
    npcN = 0
    if #npcList == 0 then return end
    local bx, by, bz, ii, ij, ik, ir = worldFrame()
    if not bx then return end
    local b = NPC_BODY
    -- EVERY FRAME the person nearest the player, and every other frame one of the others in turn as well: the one the
    -- hands are on moves with its own bones, not a frame behind them (read every other frame, a hand on a moving arm met
    -- the arm where it had been)
    b.odd = not b.odd
    local pick, best = nil, 1e9
    for i = 1, #npcList do
        local ok, p = pcall(worldPos, npcList[i])
        if ok and p then
            local d = (p.x - bx) * (p.x - bx) + (p.y - by) * (p.y - by)
            if d < best then best, pick = d, i end
        end
    end
    if pick and b.at[pick] then pcall(npcReadBones, b.at[pick]) end
    if b.odd and #npcList > 1 then
        b.turn = b.turn % #npcList + 1
        if b.turn ~= pick and b.at[b.turn] then pcall(npcReadBones, b.at[b.turn]) end
    end
    pick = pick or 1
    -- someone a hand holds: every frame, whoever else is read
    for s = 0, 1 do
        local h = b.heldRec and b.heldRec[s]
        if h and h ~= b.at[pick] then pcall(npcReadBones, h) end
    end
    b.frame = b.frame or {}
    local fr = b.frame
    fr[1], fr[2], fr[3], fr[4], fr[5], fr[6], fr[7] = bx, by, bz, ii, ij, ik, ir
    for i = 1, #npcList do
        local ok, p = pcall(worldPos, npcList[i])
        if ok and p then
            npcN = npcN + 1
            NPX[npcN], NPY[npcN], NPZ[npcN] = qrot(ii, ij, ik, ir, p.x - bx, p.y - by, p.z - bz)
            NWX[npcN], NWY[npcN], NWZ[npcN] = p.x, p.y, p.z
            local okF, fw = pcall(worldFwd, npcList[i])
            if okF and fw then NFX[npcN], NFY[npcN] = fw.x, fw.y else NFX[npcN] = nil end
            b.at[npcN] = b.at[i]
        end
    end
end

-- One person's slots carried to this frame (world space): where each slot is now and its three axes, from where it was read
-- moved by the person's step and turn since (the slots are read a frame in two to four, the person walks every frame).
local NPC_W, NPC_X, NPC_Y, NPC_Z = {}, {}, {}, {}
-- what went to the physics hands last frame, kept while the collision view is on (it draws them): ax ay az bx by bz r
local NPC_DRAWN = { n = 0, on = false }
local function npcCarry(rec, nx, ny, nz, nfx, nfy)
    local ex, ey, ez = rec.ex or nx, rec.ey or ny, rec.ez or nz
    local c, s = 1.0, 0.0
    if rec.efx and nfx and (rec.efx * rec.efx + rec.efy * rec.efy) > 0.01 and (nfx * nfx + nfy * nfy) > 0.01 then
        local t = math.atan2(nfy, nfx) - math.atan2(rec.efy, rec.efx)
        c, s = math.cos(t), math.sin(t)
    end
    local W, X, Y, Z, Q = NPC_W, NPC_X, NPC_Y, NPC_Z, rec.q
    for i = 1, #NPC_BODY.slots do
        local k = i * 3
        local x = rec[k - 2]
        if x then
            local dx, dy = x - ex, rec[k - 1] - ey
            W[k - 2], W[k - 1], W[k] = nx + c * dx - s * dy, ny + s * dx + c * dy, nz + rec[k] - ez
            local m = i * 4
            if Q and Q[m] then
                local qi, qj, qk, qr = Q[m - 3], Q[m - 2], Q[m - 1], Q[m]
                local ax, ay, az = qrot(qi, qj, qk, qr, 1.0, 0.0, 0.0)
                X[k - 2], X[k - 1], X[k] = c * ax - s * ay, s * ax + c * ay, az
                ax, ay, az = qrot(qi, qj, qk, qr, 0.0, 1.0, 0.0)
                Y[k - 2], Y[k - 1], Y[k] = c * ax - s * ay, s * ax + c * ay, az
                ax, ay, az = qrot(qi, qj, qk, qr, 0.0, 0.0, 1.0)
                Z[k - 2], Z[k - 1], Z[k] = c * ax - s * ay, s * ax + c * ay, az
            else
                X[k - 2] = false
            end
        else
            W[k - 2] = false
        end
    end
end

-- A point of the carried slots: t of the way from slot i to slot j, then u v w along slot i's own axes. Nil when a slot
-- did not answer.
local function npcPt(i, j, t, u, v, w)
    local W, X, Y, Z = NPC_W, NPC_X, NPC_Y, NPC_Z
    local k, l = i * 3, j * 3
    if not W[k - 2] or not W[l - 2] then return nil end
    local x = W[k - 2] + (W[l - 2] - W[k - 2]) * t
    local y = W[k - 1] + (W[l - 1] - W[k - 1]) * t
    local z = W[k] + (W[l] - W[k]) * t
    if u ~= 0 or v ~= 0 or w ~= 0 then
        if not X[k - 2] then return nil end
        x = x + X[k - 2] * u + Y[k - 2] * v + Z[k - 2] * w
        y = y + X[k - 1] * u + Y[k - 1] * v + Z[k - 1] * w
        z = z + X[k] * u + Y[k] * v + Z[k] * w
    end
    return x, y, z
end

-- THE PEOPLE FOR THE PHYSICS HANDS (Natives/PhysHands): each person's capsules, world space, handed over every frame. The
-- hands stop on them and the fingers lie on them, and nobody is pushed. Each shape is put by the bones it lies on, turned
-- with them (the rig's frames: the spine's and the head's X up their bone, Y to the back, Z to the right; an arm's and a
-- leg's X down to the next joint on the left and up from it on the right):
--   * the head, a skull (back of it 8 cm behind the head's joint, the forehead 12 cm ahead, 16 cm across) and the face
--     and jaw ahead of it and below; the neck from between the shoulders up to it;
--   * the trunk, two columns side by side down the spine's joints (the hips, the spine, the chest, above it), so it bends
--     and twists with the spine: a chest is wider than it is deep, and the spine is near the back;
--   * the arms joint to joint, and the hand on from the wrist the way the hand points; the thighs from the hip joints (beside
--     and under the hips bone), the shins to the ankle, the feet from the heel the way the foot points.
-- A woman's are slighter, a big man's and a fat one's wider; a woman's chest stands out further.
-- Each capsule goes with an id the physics hands keep a hold by: the person's (rec.uid) times 32 plus the capsule's place
-- among theirs, 0 for a part not to be taken hold of (the shins and the feet). The place is counted for every capsule
-- tried, sent or not: counted only for those sent, a slot that did not answer for a frame moved every capsule after it
-- down one, and a hand on an arm found itself holding the next capsule (2026-11-10).
local npcUid, npcPart = 0, 0
local function npcSend(send, i1, j1, t1, u1, v1, w1, i2, j2, t2, u2, v2, w2, r, nogrip)
    npcPart = npcPart + 1
    if NPC_BODY.kinds then NPC_BODY.kinds[npcPart] = NPC_BODY.kind end
    if NPC_BODY.grips then NPC_BODY.grips[npcPart] = NPC_BODY.grip end
    local ax, ay, az = npcPt(i1, j1, t1, u1, v1, w1)
    if not ax then return end
    local bx, by, bz = npcPt(i2, j2, t2, u2, v2, w2)
    if not bx then return end
    send(ax, ay, az, bx, by, bz, r, nogrip)
end

local function npcFoot(send, heel, right, nfx, nfy, r)
    npcPart = npcPart + 1
    local W, Y = NPC_W, NPC_Y
    local k = heel * 3
    if not W[k - 2] then return nil end
    -- the way the foot points, level: the heel's Y forward on the left, its -Y on the right; the person's own when the
    -- foot stands on its toes
    local fx, fy = 0.0, 0.0
    if Y[k - 2] then fx, fy = Y[k - 2], Y[k - 1] end
    if right then fx, fy = -fx, -fy end
    local l = math.sqrt(fx * fx + fy * fy)
    if l < 0.3 then
        if not nfx then return nil end
        fx, fy, l = nfx, nfy, math.sqrt(nfx * nfx + nfy * nfy)
        if l < 0.1 then return nil end
    end
    fx, fy = fx / l, fy / l
    local x, y, z = W[k - 2], W[k - 1], W[k]
    send(x, y, z + 0.045, x + fx * 0.17, y + fy * 0.17, z + 0.035, r, true)
    return x, y, z
end

local function npcBody(rec, send, nx, ny, nz, nfx, nfy)
    npcCarry(rec, nx, ny, nz, nfx, nfy)
    local kind = rec.kind or ''
    local woman = kind:find('Woman', 1, true) ~= nil
    local ts, ls, hs = 1.0, 1.0, 1.0
    if woman then ts, ls, hs = 0.92, 0.88, 0.95
    elseif kind:find('Fat', 1, true) then ts, ls = 1.3, 1.1
    elseif kind:find('Big', 1, true) or kind:find('Large', 1, true) then ts, ls, hs = 1.15, 1.15, 1.05 end
    -- 1 Head, 2 Chest, 3 Hips, 4 5 the arms, 6 7 the forearms, 8 9 the hands, 10 11 the knees, 12 13 the heels, 14 the spine
    -- NPC_BODY.kind: the part of the body each capsule is pulled by, when a physics hand holds it (src/Anim/NpcArmGrip.cpp);
    -- NPC_BODY.grip: the grasp the fingers take on it (src/Anim/GraspPose.cpp GraspPerson): 1 round it like a can (an arm,
    -- a shoulder's edge, a thigh), 2 so with the fingers wide (the neck), 3 gently (a hand), 4 the palm on it (the face,
    -- the head, the chest, the back); 6 the hips: round their side, the palm behind or before; 7 a thigh: round it, the palm
    -- on the buttock behind its top (K.npcGrabFollow)
    NPC_BODY.kind = 4
    NPC_BODY.grip = 4
    npcSend(send, 1, 1, 0, 0.09, 0.005, 0, 1, 1, 0, 0.09, -0.045, 0, 0.078 * hs)          -- skull
    npcSend(send, 1, 1, 0, 0.05, -0.07, 0, 1, 1, 0, -0.035, -0.075, 0, 0.050 * hs)        -- face, jaw
    NPC_BODY.grip = 2
    npcSend(send, 2, 2, 0, 0.15, 0.01, 0, 1, 1, 0, 0.02, -0.01, 0, 0.052 * ls)            -- neck
    -- the trunk: as wide as a man's hips and chest (34-36 cm) and as deep (22-24 cm), the spine 5-6 cm under the back;
    -- the shoulders from the top of the chest out to the arm's joint, so a hand on a shoulder rests on it and not in the
    -- gap between the chest and the arm
    NPC_BODY.kind = 5
    for side = -1, 1, 2 do
        local arm = side < 0 and 4 or 5
        NPC_BODY.grip = 6
        npcSend(send, 3, 3, 0, -0.04, -0.02, side * 0.075 * ts, 14, 14, 0, 0, -0.05, side * 0.065 * ts, 0.10 * ts)
        NPC_BODY.grip = 4
        npcSend(send, 14, 14, 0, 0, -0.05, side * 0.065 * ts, 2, 2, 0, 0, -0.055, side * 0.075 * ts, 0.10 * ts)
        npcSend(send, 2, 2, 0, 0, -0.055, side * 0.075 * ts, 2, 2, 0, 0.11, -0.045, side * 0.08 * ts, 0.095 * ts)
        NPC_BODY.grip = 1
        npcSend(send, 2, 2, 0, 0.13, -0.03, side * 0.11 * ts, arm, arm, 0, 0, 0, 0, 0.055 * ls)
    end
