-- props bounce off the body. On foot that is right. Mounted, the body is parked inside the seat, the door and the
-- dashboard, so every one of those contacts is an interpenetration the solver has to resolve; the player is carried
-- by the vehicle and cannot move, so the only thing left to push is the vehicle. Hence a car that leaves the ground
-- the moment you get in.
--
-- The capsules come from the ARCHIVE, not from this module, so turning the collision solve off does not remove them
-- (the same reason the weapon stays physical with COLL_ON false). They have to be switched off on the components
-- themselves, and back on when the player gets out.
--
-- Handles do not survive the toggle, so the queries-off scan is invalidated with it.
--
-- CAPS_PHYS_ON is the same switch used as a bisect handle: false keeps the capsules off everywhere, not just in a
-- vehicle, which is how "are the body capsules behind this crash" gets answered without touching the archive. The
