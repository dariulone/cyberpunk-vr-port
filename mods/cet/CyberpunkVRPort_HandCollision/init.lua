local function qmul(ai, aj, ak, ar, bi, bj, bk, br)
    return ar * bi + ai * br + aj * bk - ak * bj,
           ar * bj - ai * bk + aj * br + ak * bi,
           ar * bk + ai * bj - aj * bi + ak * br,
           ar * br - ai * bi - aj * bj - ak * bk
end

-- Whether the weapon in the hand is a gun. Asked again until it says yes: one just drawn answers no for a few frames.
local rangedKey, rangedAnswer, rangedWait = nil, false, 0
local function weaponRanged(w)
    local key = w:GetEntityID().hash
    if key ~= rangedKey then rangedKey, rangedAnswer, rangedWait = key, false, 0 end
    if rangedAnswer then return true end
    if rangedWait > 0 then
        rangedWait = rangedWait - 1
        return false
    end
    rangedWait = 20
    rangedAnswer = w:IsRanged() == true
    return rangedAnswer
end

