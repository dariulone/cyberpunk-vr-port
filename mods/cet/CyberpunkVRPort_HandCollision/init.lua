-- POOLED, FLAT SCRATCH, allocated once and reused for the session. A capsule is one table of scalars rather
-- than a table holding two endpoint tables; the candidate list is parallel arrays rather than a table per pair.
-- See cause 5: this mattered more than any of the maths above it.

local POOL, poolN = {}, 0

local function cap(id, r, ax, ay, az, bx, by, bz, label)
    poolN = poolN + 1
    local c = POOL[poolN]
    if not c then c = {}; POOL[poolN] = c end
    c.id, c.r, c.label = id, r, label
    c.ax, c.ay, c.az, c.bx, c.by, c.bz = ax, ay, az, bx, by, bz
    c.cx, c.cy, c.cz = (ax + bx) * 0.5, (ay + by) * 0.5, (az + bz) * 0.5
    local dx, dy, dz = bx - ax, by - ay, bz - az
    c.e = math.sqrt(dx * dx + dy * dy + dz * dz) * 0.5 + r
    return c
end

