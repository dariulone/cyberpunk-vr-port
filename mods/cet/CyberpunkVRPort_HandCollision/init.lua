-- event per mod, and hosting the recorder's onUpdate here silently replaced the main loop above -- the
-- dead-grip bug that cost three sessions. Never host a second per-frame job in this file.

-- ---------------------------------------------------------------------------------------------------------
-- MAGAZINE TUNER, in the CET overlay.
--
-- Every constant in a weapon config is measured, and it stays that way -- but the game's hand RE-GRIPS the
-- magazine on the way in (measured: its origin sits 4.3-6.7 cm from the hold slot while it is pushed home and
-- 12.5 cm at the frame it seats, and that last one is already after the hand let go). A VR hand holds one
-- relation, so exactly one number here cannot come from the animation: which of them to wear. This window is
-- where that gets decided by the eye that has to look at it, and PRINTED, so it goes back into the config as a
-- constant beside the measured ones rather than living as a slider forever.

registerForEvent('onShutdown', function()
    pcall(function() VRHandStopModel(0, false, Vector4.new(0, 0, 0, 0)) end)
    pcall(function() VRHandStopModel(1, false, Vector4.new(0, 0, 0, 0)) end)
    -- the wrist rotation lock is plugin-side state; left on through a mod reload it would freeze the hand's aim
    pcall(function() VRHandStopRot(0, 0, 0, 0, 0, 1) end)
    pcall(function() VRHandStopRot(1, 0, 0, 0, 0, 1) end)
    pcall(function() VRHandStopDeadband(0.02) end)   -- leave the plugin as it ships
end)
