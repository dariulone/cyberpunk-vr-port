local function npcTugOne(rec, px, py, step)
    local e = rec.e
    local now = npcClock
    if rec.tugAt and now - rec.tugAt < NPC_TUG_EVERY then return 0.0 end
    if Game.GetWorkspotSystem():IsActorInWorkspot(e) then return 0.0 end
    local p = e:GetWorldPosition()
    -- walking on their own: where they are now against where they were put last
    if rec.tugAt and now - rec.tugAt < 0.3 and rec.tugX then
        local dx, dy = p.x - rec.tugX, p.y - rec.tugY
        if math.sqrt(dx * dx + dy * dy) / (now - rec.tugAt) > 0.6 then
            rec.tugX, rec.tugY, rec.tugAt = p.x, p.y, now
            return 0.0
        end
    end
    local l = math.sqrt(px * px + py * py)
    local nx, ny = p.x + px / l * step, p.y + py / l * step
    local cmd = AITeleportCommand.new()
    cmd.position = Vector4.new(nx, ny, p.z, 1.0)
    cmd.rotation = e:GetWorldYaw()
    cmd.doNavTest = false
    e:GetAIControllerComponent():SendCommand(cmd)
    rec.tugX, rec.tugY, rec.tugAt = nx, ny, now
    return step
end
local function npcTug()
