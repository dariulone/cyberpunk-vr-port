-- A capsule's two model-space endpoints, as six scalars. ox/oy/oz overrides the bone's own position.
local function endpoints(c, ox, oy, oz)
    local px, py, pz, qi, qj, qk, qr = bone(c.index)
    if not px then return nil end
    local bx, by, bz = ox or px, oy or py, oz or pz
    local xx, xy, xz = qrot(qi, qj, qk, qr, 1.0, 0.0, 0.0)
    local yx, yy, yz = qrot(qi, qj, qk, qr, 0.0, 1.0, 0.0)
    local zx, zy, zz = qrot(qi, qj, qk, qr, 0.0, 0.0, 1.0)
    local cx = bx + xx * c.cx + yx * c.cy + zx * c.cz
    local cy = by + xy * c.cx + yy * c.cy + zy * c.cz
    local cz = bz + xz * c.cx + yz * c.cy + zz * c.cz
    local h = c.half
    return cx - xx * h, cy - xy * h, cz - xz * h,
           cx + xx * h, cy + xy * h, cz + xz * h
end

-- Closest points between two segments, all scalars: clamped solve plus the refinement pass that makes it correct
-- when the nearest approach lands on an endpoint.
local function segClosest(pax, pay, paz, pbx, pby, pbz, qax, qay, qaz, qbx, qby, qbz)
    local ux, uy, uz = pbx - pax, pby - pay, pbz - paz
    local vx, vy, vz = qbx - qax, qby - qay, qbz - qaz
    local wx, wy, wz = pax - qax, pay - qay, paz - qaz
    local a = ux * ux + uy * uy + uz * uz
    local b = ux * vx + uy * vy + uz * vz
    local c = vx * vx + vy * vy + vz * vz
    local d = ux * wx + uy * wy + uz * wz
    local e = vx * wx + vy * wy + vz * wz
    local den = a * c - b * b
    local sc = 0.0
    if den > 1e-9 then sc = (b * e - c * d) / den end
    if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    local tc = 0.0
    if c > 1e-9 then
        tc = (e + b * sc) / c
        if tc < 0.0 then tc = 0.0 elseif tc > 1.0 then tc = 1.0 end
    end
    if a > 1e-9 then
        sc = (b * tc - d) / a
        if sc < 0.0 then sc = 0.0 elseif sc > 1.0 then sc = 1.0 end
    end
    return pax + ux * sc, pay + uy * sc, paz + uz * sc,
           qax + vx * tc, qay + vy * tc, qaz + vz * tc
end

-- Finger capsules: slot named vrp_f_<finger><joint>_<l|r>.
local function fingerSide(slot)
    if slot:sub(1, 6) ~= 'vrp_f_' then return nil end
    local tail = slot:sub(-2)
    if tail == '_l' then return 0 elseif tail == '_r' then return 1 end
    return nil
end

-- Which body capsules may stop the rig hanging off the wrist of `side`. Excluded: everything that wrist's own IK
-- places -- upper arm, forearm, hand -- because a capsule that moves when the wrist is pushed is a feedback loop
-- (cause 1). And every hand and finger capsule of EITHER side, because they all hang off a hand bone that carries
-- a clamp; those come back through ridingSet, placed from a raw target instead.
local OBST, HAND, RIDE = {}, {}, {}
for side = 0, 1 do
    OBST[side] = { n = 0 }
    RIDE[side] = { n = 0 }
    for i = 1, #CAPS do
        local c = CAPS[i]
        c.uid = i
        if c.slot ~= ARM_SLOT[side] and c.slot ~= FORE_SLOT[side]
           and c.slot ~= HAND_SLOT[0] and c.slot ~= HAND_SLOT[1]
           and fingerSide(c.slot) == nil then
            push(OBST[side], c)
        end
        if c.slot == HAND_SLOT[side] then HAND[side] = c end
        if c.slot == HAND_SLOT[side] or fingerSide(c.slot) == side then push(RIDE[side], c) end
    end
end

-- Contact ids: a body or finger capsule takes its index in CAPS, a gun capsule 100 + its index. The pair
-- (mover, obstacle) tells the roles apart, so the same capsule may appear as both. Integers rather than
-- concatenated strings -- one string per candidate pair was hundreds of allocations a frame.
local GUN_ID = 100

-- PEOPLE. A query does not answer for an NPC, whose capsule moves but is not simulated, so they are obstacles of the
-- solve, like the player's own body. Listed four times a second, and placed every frame. Not for a melee weapon, or a
-- swing would stop before it hits.
--
-- FROM THEIR BONES. An NPC's slot component binds slots to real bones (Item_Attachment_Slot: Head -> Head, Chest -> Spine3,
-- LegLeft -> LeftLeg, and so on), and those answer with the live pose, so a capsule between two of them sits, crouches
-- and swings its arms with the person. The radii are the ragdoll's own (man_base.rig, ragdollDesc): that body only
-- exists once someone is thrown, so its shapes are borrowed and not asked. One person's slots are read per frame, in turn.
-- Without that component, three capsules from the feet up, which is a standing person.
local NPC_ID, NPC_RANGE, NPC_MAX, NPC_EVERY = 200, 1.6, 4, 0.25
local NPC_PARTS = {
    { 0.12, 0.10, 0.85 },   -- legs: radius, from, to (m above the feet)
    { 0.15, 0.90, 1.42 },   -- body
    { 0.11, 1.56, 1.66 },   -- head
}
local npcList, npcAt, npcClock = {}, -1.0, 0.0
local NPX, NPY, NPZ, npcN = {}, {}, {}, 0
local NPC_SWAY = 0.02         -- m
local NPC_BODY = { recs = {}, at = {}, turn = 0, seen = false,
    slots = { 'Head', 'Chest', 'Hips', 'LeftArm', 'RightArm', 'LeftForeArm', 'RightForeArm', 'LeftHand', 'RightHand',
              'LegLeft', 'LegRight', 'LeftFoot', 'RightFoot' },
    -- joint, joint, radius, and how far the capsule's end sits above the joint
    -- The ragdoll's radii, wider on the trunk and legs: clothes and flesh stand further off a bone than its ragdoll does.
    bones = { { 3, 2, 0.145 }, { 2, 1, 0.060 }, { 1, 1, 0.095, 0.09 }, { 2, 4, 0.070 }, { 2, 5, 0.070 },
              { 4, 6, 0.060 }, { 5, 7, 0.060 }, { 6, 8, 0.050 }, { 7, 9, 0.050 },
              { 3, 10, 0.105 }, { 3, 11, 0.105 }, { 10, 12, 0.080 }, { 11, 13, 0.080 } },
}

local function npcAlive(e)
    return e:IsA('NPCPuppet') and ScriptedPuppet.IsAlive(e)
end

local function npcRefresh()
    local list = {}
    pcall(function()
        local pl = Game.GetPlayer()
        local q = TSQ_ALL()
        q.maxDistance = NPC_RANGE
        q.testedSet = TargetingSet.Complete
        q.ignoreInstigator = true
        local ok, parts = Game.GetTargetingSystem():GetTargetParts(pl, q)
        if not ok or not parts then return end
        local seen = {}
        for _, part in ipairs(parts) do
            local c = part:GetComponent()
            local e = c and c:GetEntity()
            if e then
                local id = tostring(e:GetEntityID().hash)
                if not seen[id] then
                    seen[id] = true
                    local okA, alive = pcall(npcAlive, e)
                    if okA and alive and #list < NPC_MAX then list[#list + 1] = e end
                end
            end
        end
    end)
    npcList = list
    -- what is known of each person is kept by who they are, since the list is rebuilt four times a second
    local b, recs = NPC_BODY, {}
    for i = 1, #list do
        local id = tostring(list[i]:GetEntityID().hash)
        recs[id] = b.recs[id] or { n = 0 }
        recs[id].e = list[i]
        b.at[i] = recs[id]
    end
    for i = #list + 1, NPC_MAX do b.at[i] = nil end
    b.recs = recs
end

-- The slots of one person, world space.
local function npcReadBones(rec)
    local b = NPC_BODY
    if not rec.comp then
        if rec.noComp then return end
        local cs = Game.VREntityComponents(rec.e)
        for i = 1, #cs do
            if NameToString(cs[i]:GetName()) == 'Item_Attachment_Slot' then rec.comp = cs[i] break end
        end
        if not rec.comp then rec.noComp = true return end
    end
    if not b.names then
        b.names = {}
        for i = 1, #b.slots do b.names[i] = CName.new(b.slots[i]) end
    end
    local n = 0
    for i = 1, #b.slots do
        local o, found, tr = pcall(slotTransform, rec.comp, b.names[i])
        local okP, wp = false, nil
        if o and found and tr then okP, wp = pcall(slotPosition, tr) end
        if okP and wp then
            n = n + 1
            -- A joint stays put until it has moved more than the sway of someone standing still, and then follows at that distance. A
            -- hand resting on a head was carried about by every breath, and round the curve of the capsule besides.
            local ox, oy, oz = rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3]
            if ox then
                local dx, dy, dz = wp.x - ox, wp.y - oy, wp.z - oz
                local d = math.sqrt(dx * dx + dy * dy + dz * dz)
                if d > NPC_SWAY then
                    local k = 1.0 - NPC_SWAY / d
                    rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3] = ox + dx * k, oy + dy * k, oz + dz * k
                end
            else
                rec[i * 3 - 2], rec[i * 3 - 1], rec[i * 3] = wp.x, wp.y, wp.z
            end
        else
            rec[i * 3 - 2] = false
        end
    end
    rec.n = n
    if not b.seen and n > 0 then
        b.seen = true
        pcall(function() spdlog.info(string.format('[HandColl] npc bones: %d of %d slots answer', n, #b.slots)) end)
    end
end

-- Where they stand this frame, in model space.
local function npcPlace(dt)
    npcClock = npcClock + dt
    if npcClock - npcAt >= NPC_EVERY then
        npcAt = npcClock
        npcRefresh()
    end
    npcN = 0
    if #npcList == 0 then return end
    local bx, by, bz, ii, ij, ik, ir = worldFrame()
    if not bx then return end
    local b = NPC_BODY
    b.turn = b.turn % #npcList + 1
    if b.at[b.turn] then pcall(npcReadBones, b.at[b.turn]) end
    b.frame = b.frame or {}
    local fr = b.frame
    fr[1], fr[2], fr[3], fr[4], fr[5], fr[6], fr[7] = bx, by, bz, ii, ij, ik, ir
    for i = 1, #npcList do
        local ok, p = pcall(worldPos, npcList[i])
        if ok and p then
            npcN = npcN + 1
            NPX[npcN], NPY[npcN], NPZ[npcN] = qrot(ii, ij, ik, ir, p.x - bx, p.y - by, p.z - bz)
            b.at[npcN] = b.at[i]
        end
    end
end

-- One person's capsules, in model space. False when the slots are not there to go by.
local function npcCapsules(i, out)
    local b = NPC_BODY
    local rec = b.at[i]
    if not rec or rec.n < 8 then return false end
    local fr = b.frame
    local bx, by, bz, ii, ij, ik, ir = fr[1], fr[2], fr[3], fr[4], fr[5], fr[6], fr[7]
    for k = 1, #b.bones do
        local part = b.bones[k]
        local j1, j2 = part[1] * 3, part[2] * 3
        if rec[j1 - 2] and rec[j2 - 2] then
            local ax, ay, az = qrot(ii, ij, ik, ir, rec[j1 - 2] - bx, rec[j1 - 1] - by, rec[j1] - bz)
            local cx, cy, cz = qrot(ii, ij, ik, ir, rec[j2 - 2] - bx, rec[j2 - 1] - by, rec[j2] - bz)
            if part[4] then cz = cz + part[4]; az = az + part[4] end
            push(out, cap(NPC_ID + (i - 1) * 16 + k, part[3], ax, ay, az, cx, cy, cz, 'npc'))
        end
    end
    return true
end

-- `withoutOther`: the other arm is on this hand's gun, placed by this very wrist as its support, so it is an obstacle that
-- moves when this hand is pushed: cause 1 again, on a pistol and a shotgun, where that forearm lies against the gun hand.
local function buildObstacles(side, out, withoutOther)
    out.n = 0
    local list = OBST[side]
    local otherArm, otherFore = ARM_SLOT[1 - side], FORE_SLOT[1 - side]
    for i = 1, list.n do
        local c = list[i]
        if not withoutOther or (c.slot ~= otherArm and c.slot ~= otherFore) then
            local ax, ay, az, bx, by, bz = endpoints(c)
            if ax then push(out, cap(c.uid, c.r, ax, ay, az, bx, by, bz, c.slot)) end
        end
    end
    for i = 1, npcN do
        if not npcCapsules(i, out) then
            local x, y, z = NPX[i], NPY[i], NPZ[i]
            for k = 1, #NPC_PARTS do
                local part = NPC_PARTS[k]
                push(out, cap(NPC_ID + (i - 1) * 16 + k, part[1], x, y, z + part[2], x, y, z + part[3], 'npc'))
            end
        end
    end
    return out
end

-- The palm and every phalanx of `side`, as they would sit with that wrist at x,y,z.
--
-- EXACT rather than an approximation: the finger bones are descendants of the hand bone, so the whole set is
-- rigid with respect to the wrist, and the clamp only ever TRANSLATES the wrist. The set as measured now, moved
-- by (x,y,z) minus the hand bone's position, IS the set with the wrist at x,y,z -- and that subtraction cancels
-- whatever hold was active when the bones were read. So finger geometry stays a function of tracking and of the
-- animated curl, never of last frame's output. The curl matters: a closed fist collides as a fist.
local function ridingSet(side, x, y, z, out)
    local h = HAND[side]
    if not h then return out end
    local hx, hy, hz = bone(h.index)
    if not hx then return out end
    local dx, dy, dz = x - hx, y - hy, z - hz
    local list = RIDE[side]
    for i = 1, list.n do
        local c = list[i]
        local ax, ay, az, bx, by, bz = endpoints(c)
        if ax then
            push(out, cap(c.uid, c.r, ax + dx, ay + dy, az + dz, bx + dx, by + dy, bz + dz, c.slot))
        end
    end
    return out
end

-- The weapon's capsules as they would sit with the holder's wrist at x,y,z. Same exactness argument as above.
local function gunAt(side, x, y, z, out)
    if WGN == 0 then return out end
    local h = HAND[side]
    if not h then return out end
    local hx, hy, hz = bone(h.index)
    if not hx then return out end
    local dx, dy, dz = x - hx, y - hy, z - hz
    for i = 1, WGN do
        local cx, cy, cz = WGX[i] + dx, WGY[i] + dy, WGZ[i] + dz
        local ex, ey, ez = WGDX[i], WGDY[i], WGDZ[i]
        push(out, cap(GUN_ID + i, WCAPS[i].r,
                      cx - ex, cy - ey, cz - ez, cx + ex, cy + ey, cz + ez, WCAPS[i].bone))
    end
    return out
end

-- Translate a RIGID SET of capsules until none of them overlaps any obstacle, and return the translation.
local function resolveRig(side, movers, segs)
    if movers.n == 0 or segs.n == 0 then return 0.0, 0.0, 0.0 end
    local mem = stick[side]
    local tx, ty, tz = 0.0, 0.0, 0.0

    -- COARSE CULL: one sphere test per obstacle against the whole mover set. The pairwise pass below is
    -- movers x obstacles -- 74 x 90 with fingers and a 58-capsule weapon -- and no amount of slack tuning
    -- changes that product; measured, tightening the pairwise slack from 0.15 to 0.05 moved the pair count from
    -- 722 to 806, because the weapon had meanwhile gone from 28 capsules to 58. Culling the obstacles once does
    -- change it. Grown by CULL because this list is built once and must survive the whole hold, measured as far
    -- as 0.166 m.
    NEAR.n = 0
    local cx, cy, cz = 0.0, 0.0, 0.0
    for i = 1, movers.n do
        local m = movers[i]
        cx, cy, cz = cx + m.cx, cy + m.cy, cz + m.cz
    end
    local inv = 1.0 / movers.n
    cx, cy, cz = cx * inv, cy * inv, cz * inv
    local rad = 0.0
    for i = 1, movers.n do
        local m = movers[i]
        local dx, dy, dz = m.cx - cx, m.cy - cy, m.cz - cz
        local d = math.sqrt(dx * dx + dy * dy + dz * dz) + m.e
        if d > rad then rad = d end
    end
    rad = rad + CULL
    for i = 1, segs.n do
        local s = segs[i]
        local dx, dy, dz = s.cx - cx, s.cy - cy, s.cz - cz
        local reach = rad + s.e
        if dx * dx + dy * dy + dz * dz <= reach * reach then push(NEAR, s) end
    end
    if NEAR.n == 0 then return 0.0, 0.0, 0.0 end

    local n = 0
    local function broadphase()
        n = 0
        for mi = 1, movers.n do
            local m = movers[mi]
            local mx, my, mz = m.cx + tx, m.cy + ty, m.cz + tz
            local me, mid = m.e, m.id * 512
            for si = 1, NEAR.n do
                local s = NEAR[si]
                local dx, dy, dz = mx - s.cx, my - s.cy, mz - s.cz
                local reach = me + s.e + BROAD
                if dx * dx + dy * dy + dz * dz <= reach * reach then
                    n = n + 1
                    CD_M[n], CD_S[n], CD_KEY[n] = m, s, mid + s.id
                end
            end
        end
        if n > candMax then candMax = n end
        return n
    end

    if broadphase() == 0 then return 0.0, 0.0, 0.0 end
    local bx, by, bz = 0.0, 0.0, 0.0

    for _ = 1, PASSES do
        -- SEQUENTIAL PROJECTION: each contact is answered in full the moment it is found, and the next one is
        -- evaluated against the already-moved rig. Count-independent, unlike an average -- see cause 4.
        local deepest, dm, ds = 0.0, nil, nil
        for ci = 1, n do
            local m, s, key = CD_M[ci], CD_S[ci], CD_KEY[ci]
            local hx, hy, hz, qx, qy, qz = segClosest(
                m.ax + tx, m.ay + ty, m.az + tz, m.bx + tx, m.by + ty, m.bz + tz,
                s.ax, s.ay, s.az, s.bx, s.by, s.bz)
            local sx, sy, sz = hx - qx, hy - qy, hz - qz
            local dist = math.sqrt(sx * sx + sy * sy + sz * sz)
            local need = m.r + s.r
            local mm = mem[key]
            local limit = need
            if mm then limit = need + RELEASE_MARGIN end
            if dist >= limit then
                if mm then mem[key] = nil end
            else
                local ux, uy, uz
                if dist > 1e-5 then ux, uy, uz = sx / dist, sy / dist, sz / dist
                else ux, uy, uz = 0.0, 0.0, 1.0 end
                if mm then
                    -- keep leaving by the side it first left by; the shortest way out flips once the mover is
                    -- past the axis, and following that flip teleported the hand through the chest
                    if (mm[1] * ux + mm[2] * uy + mm[3] * uz) < 0.0 then
                        ux, uy, uz = mm[1], mm[2], mm[3]
                        dist = -(sx * ux + sy * uy + sz * uz)
                    end
                else
                    mem[key] = { ux, uy, uz }
                end
                local depth = need - dist
                if depth > 0.0 then
                    local step = depth * OMEGA
                    tx, ty, tz = tx + ux * step, ty + uy * step, tz + uz * step
                    if depth > deepest then deepest, dm, ds = depth, m, s end
                end
            end
        end
        if dm then worstM[side], worstS[side] = dm.label, ds.label end
        if deepest <= SETTLED then break end
        local ddx, ddy, ddz = tx - bx, ty - by, tz - bz
        if ddx * ddx + ddy * ddy + ddz * ddz > BROAD * BROAD * 0.25 then
            bx, by, bz = tx, ty, tz
            if broadphase() == 0 then break end
        end
    end
    return tx, ty, tz
end

-- WHICH HAND HOLDS THE WEAPON, latched for the life of that weapon instance. Decided per frame as "nearer wrist"
-- it flipped whenever the free hand came to the grip -- which is where the trigger is -- and each flip swapped
-- which hand was frozen. A weapon does not change hands while equipped.
local HOLDER_DROP = 0.30    -- m: beyond this from the grip, the latched hand plainly is not holding it
local holderSide, holderEnt = nil, nil
local dbgDL, dbgDR = -1.0, -1.0

-- WHICH HAND HOLDS THE GUN, asked of the game rather than guessed from geometry.
--
-- The distance test below picks whichever wrist is nearer the grip, and that is wrong exactly when it matters: a
-- hand reaching for the MAGAZINE passes closer to the grip than the hand holding the weapon. The holder then
-- flipped to the free hand -- the gun visibly snapped across to it (the pistol went under the left hand) and the
-- reload's magnet, which always drives the hand that is NOT the holder, started pulling the real gun hand.
--
-- The game already knows the answer: a held weapon is attached to `ItemAttachmentSlots.WeaponRight` or
-- `.WeaponLeft`, and `GetItemInSlot` returns it. Verified live -- the active weapon's entity id came back from
-- WeaponRight and from nowhere else. Cached per weapon, because it cannot change without the weapon changing.
local slotHolder, slotHolderFor = nil, nil
local function holderFromSlot()
    local pl = Game.GetPlayer()
    local w = pl and pl:GetActiveWeapon()
    if not w then slotHolder, slotHolderFor = nil, nil; return nil end
    local okId, wid = pcall(function() return w:GetEntityID().hash end)
    if not okId then return nil end
    if slotHolderFor == wid then return slotHolder end
    local ts = Game.GetTransactionSystem()
    if not ts then return nil end
    local found = nil
    for _, e in ipairs({ { 1, 'AttachmentSlots.WeaponRight' }, { 0, 'AttachmentSlots.WeaponLeft' } }) do
        local ok, it = pcall(function() return ts:GetItemInSlot(pl, TweakDBID.new(e[2])) end)
        if ok and it then
            local ok2, h = pcall(function() return it:GetEntityID().hash end)
            if ok2 and h == wid then found = e[1]; break end
        end
    end
    if found ~= nil then slotHolder, slotHolderFor = found, wid end
    return found
end

local function holderOf(rl, rr)
    -- the game's own answer wins; the geometry below is only for when it has none to give
    local s = holderFromSlot()
    if s ~= nil then
        holderSide, holderEnt = s, slotEnt
        local function d0(v)
            if not v then return -1.0 end
            local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
            return math.sqrt(dx * dx + dy * dy + dz * dz)
        end
        dbgDL, dbgDR = d0(rl), d0(rr)
        return s
    end
    if slotEnt ~= holderEnt then holderSide, holderEnt = nil, slotEnt end
    local function dist(v)
        local dx, dy, dz = v.x - WGRX, v.y - WGRY, v.z - WGRZ
        return math.sqrt(dx * dx + dy * dy + dz * dz)
    end
    dbgDL = rl and dist(rl) or -1.0
    dbgDR = rr and dist(rr) or -1.0

    if holderSide ~= nil then
        local d = (holderSide == 0) and dbgDL or dbgDR
        if d >= 0.0 and d <= HOLDER_DROP then return holderSide end
        holderSide = nil
    end

    -- Right by default, and the left has to WIN by a margin. Cyberpunk holds a weapon in the right hand; the
    -- left is only ever a support hand, and it can sit as close to the grip as the right one does. A tie going
    -- the wrong way costs the whole feature, since the true holder then gets pushed off its own weapon.
    -- WGRX has not been written since the weapon's capsules moved to their own bones, so this distance is from the player's
    -- feet and the left hand won whenever it was the lower one: as the support hand, it is then left out of the solve, and
    -- the gun with it. The slot lookup above is the answer; without one, the right hand is.
    if rr then holderSide = 1
    elseif rl then holderSide = 0 end
    return holderSide
end

