        local ok, item = pcall(function() return ts:GetItemInSlot(p, TweakDBID.new(slot)) end)
        if not ok or not item then return nil end
        local okN, name = pcall(function() return TDBID.ToStringDEBUG(ItemID.GetTDBID(item:GetItemID())) end)
        return (okN and name or ''):lower()
    end
    local outer, inner = worn('AttachmentSlots.Torso'), worn('AttachmentSlots.Chest')
