registerForEvent('onUpdate', function(dt)
    dbgAcc = dbgAcc + (dt or 0.016)
    if dbgAcc >= 1.0 then
        dbgAcc = 0.0
        traceOn = dbgOn()
        if traceOn then
            pcall(function() spdlog.info(string.format('[Tick] stage=%s %s ownHand=%s collOn=%s',
                dbgStage, dbgNote,
                (type(GetVRSharedSlot) == 'function') and tostring(GetVRSharedSlot(162)) or '?',
                tostring(COLL_ON))) end)
        end
    end
    local t0 = (os and os.clock) and os.clock() or nil
    dbgStage, dbgNote = 'natives', ''
    if type(VRHandRawModel) ~= 'function' or type(VRHandStopModel) ~= 'function' then return end
    if type(VRBoneModelPos) ~= 'function' or type(VRBoneModelRot) ~= 'function' then return end
    if type(SetVRDiagCapture) ~= 'function' then return end
    ensureCapture()
    ensureDeadband()
    -- The census is NOT started any more: identification is by bone name in the hook, and the census recorded
    -- every skeleton in the world on the hot path for nothing.
    if not censusStarted then censusStarted, censusAt = true, 0.0 end

    gen = gen + 1
    poolN = 0

    -- THE SLOT STARTS AT 0, WHICH READS AS "THE LEFT WRIST IS TAKEN". The reload writes it only on a change, and from
    -- nobody to nobody is not one, so until the first magazine the left hand was left out of this solve altogether.
    if not ownerCleared and type(SetVRReloadOwnedHand) == 'function' then
        ownerCleared = pcall(function() SetVRReloadOwnedHand(-1) end)
    end

    local collMask = 0
    if type(VRHandCollision) == 'function' then
        local okMask, m = pcall(VRHandCollision)
        if okMask and m then collMask = m end
    end
    COLL_ON = collMask % 4 ~= 0
    if not COLL_ON then HC.suspend() end
    WORLD_ON = math.floor(collMask / 4) % 2 == 1
    local pushAllowed = math.floor(collMask / 8) % 2 == 1
    -- 64: the hands have PhysX bodies of their own (Natives/PhysHands.cpp): they push, and the template's capsules stay off
    local handBodies = math.floor(collMask / 64) % 2 == 1
    HC.setPhys(handBodies)
    if handBodies then pcall(HC.selfPad) end

    local rl, rr = VRHandRawModel(0), VRHandRawModel(1)
    dbgStage = 'hands'
    if traceOn then dbgNote = string.format('Lw=%.1f Rw=%.1f', rl and rl.w or -1, rr and rr.w or -1) end
    if rl and rl.w < 0.5 then rl = nil end
    if rr and rr.w < 0.5 then rr = nil end
    if not rl and not rr then return end
    HC.pfBegin()
    RAW[0], RAW[1] = rl, rr
    if rl then PX[0], PY[0], PZ[0] = rl.x, rl.y, rl.z end
    if rr then PX[1], PY[1], PZ[1] = rr.x, rr.y, rr.z end

    local holder = nil
    -- With the collision off the slots, and the holder, only feed the tracer's note.
    local haveGun = readWeapon(COLL_ON) > 0
    if type(VRPoseCensus) == 'function' then VRPoseCensus(-4, haveGun and 1 or 0) end
    -- Only the Silverhand has capsules (haveGun); any weapon in hand has a holder, who must not count as an empty hand.
    if (haveGun or (COLL_ON and heldWeapon() ~= nil)) and (COLL_ON or traceOn) then
        holder = holderOf(rl, rr)
        if holder ~= nil and (not RAW[holder] or not HAND[holder]) then holder = nil end
    end
    if handBodies then pcall(HC.weaponBody, holder) end

    -- COLLISION OFF (dev): release both hands so nothing clamps them, run only the physical reload, and stop.
    if not COLL_ON then
        dbgStage = 'colloff'
        if traceOn then
            dbgNote = string.format('gun=%s holder=%s slotComp=%s', tostring(haveGun), tostring(holder), tostring(slotComp ~= nil))
        end
        -- ...EXCEPT THE WRIST THE RELOAD HOLDS, and that exception is what the split cost here. While the
        -- reload lived in this file the release was safe by construction: it ran, and the reload's frame
        -- re-took its wrist two statements later in this same callback. Two mods have no guaranteed
        -- callback order, so a release can land AFTER the hold and cancel it -- which is a magnet that
        -- simply does not hold. Same rule the solve path below has always used for the owned wrist.
        local ownRel = nil
        if type(GetVRSharedSlot) == 'function' then
            local v = GetVRSharedSlot(162)
            if v == 0.0 or v == 1.0 then ownRel = math.floor(v) end
        end
        if ownRel ~= 0 then pcall(releaseHand, 0) end
        if ownRel ~= 1 then pcall(releaseHand, 1) end
        SKIP[0], SKIP[1] = true, true
        HC.handsPush(false, nil, os.clock())
        bodyCapsulesForVehicle(os.clock())
        return
    end

    
-- THE HAND THE RELOAD OWNS. While it glues a wrist to a weapon part (the slide's grip, the magazine's magnet) that
    -- wrist has exactly one writer -- the reload's -- and this solve must neither push it nor publish it. Two writers
    -- on one wrist is a shake, not a compromise: this module publishes a push-OUT of the gun every frame and the
    -- reload then writes its own hold over it, so the pin is dropped and re-taken frame after frame. And leaving the
    -- owned hand out of the solve is the same rule that killed the first shake -- nothing an IK solve places may be an
    -- obstacle for it -- since the reload deliberately holds that hand against the very part this would push it off.
    -- The flag is one frame old (the reload runs in its own mod, after this one): right, because ownership
    -- changes at the speed of a hand.
    --
    -- THROUGH SHARED SLOT [162], which is what the split cost. Two CET mods are two sandboxes and cannot see each
    -- other's tables, so the reload publishes the wrist it owns (SetVRReloadOwnedHand) and this reads it. -1 means
    -- nobody owns a wrist -- including when the reload mod is not installed at all, which is the point: this module
    -- now runs without it.
    local ownHand = nil
    if type(GetVRSharedSlot) == 'function' then
        local v = GetVRSharedSlot(162)
        if v == 0.0 or v == 1.0 then ownHand = math.floor(v) end
    end
    SKIP[0] = ownHand == 0 or collMask % 2 == 0
    SKIP[1] = ownHand == 1 or math.floor(collMask / 2) % 2 == 0

    -- WHAT THE SOLVE IS WORKING WITH, once per change: a gun that does nothing at a wall has several possible reasons, and
    -- each of them looks the same in the headset.
    local stateKey = collMask * 1000 + ((holder or 2) + 1) * 100 + ((ownHand or 2) + 1) * 10
        + (SKIP[0] and 1 or 0) + (SKIP[1] and 2 or 0) + (lastW and 4 or 0)
    if stateKey ~= HC.stateKey then
        HC.stateKey = stateKey
        pcall(function() spdlog.info(string.format('[HandColl] state mask=%d holder=%s owned=%s skipL=%s skipR=%s weapon=%s',
            collMask, tostring(holder), tostring(ownHand), tostring(SKIP[0]), tostring(SKIP[1]), tostring(lastW ~= nil))) end)
    end

    -- People, on foot, with empty hands or a gun.
    npcN = 0
    local npcOn = WORLD_ON
    if npcOn and holder ~= nil and lastW then
        local okR, ranged = pcall(HC.weaponRanged, lastW)
        npcOn = okR and ranged
    end
    HC.pf('reading')
    if npcOn then npcPlace(dt or 0.016) end
    npcPublish()
    if npcOn then npcTug() end
    HC.pf('people list')

    do
        local wx, wy, wz, wi, wj, wk, wr = worldFrame()
        if wx then HC.trackHands(dt or 0.016, wx, wy, wz, wi, wj, wk, wr) end
        if wx then
            local okH, errH = pcall(HC.hair, dt or 0.016, wx, wy, wz, wi, wj, wk, wr)
            if not okH and not HC.hairSaid then
                HC.hairSaid = true
                pcall(function() spdlog.info('[HandColl] hair: ' .. tostring(errH)) end)
            end
        end
    end
    HC.pf('tracking')

    if holder ~= nil then
        -- 1. THE HOLDER: its hand, its fingers and the whole gun, against the body. Placed from the RAW wrist, so
        --    this step depends on nothing but tracking, which is what lets the gun be pushed at all without the
        --    shake coming back.
        local h = RAW[holder]
        if not SKIP[holder] then
            LA.n = 0
            ridingSet(holder, h.x, h.y, h.z, LA)
            gunAt(holder, h.x, h.y, h.z, LA)
            local dx, dy, dz = resolveRig(holder, LA, buildObstacles(holder, LB, SKIP[1 - holder]))
            PX[holder], PY[holder], PZ[holder] = h.x + dx, h.y + dy, h.z + dz
        end

        -- 2. THE FREE HAND: against the body, against the gun where step 1 just put it, and against the holder's
        --    hand and fingers. One sequential solve over all three, so the answer satisfies them together.
        local free = 1 - holder
        local f = RAW[free]
        if f and HAND[free] and not SKIP[free] then
            buildObstacles(free, LB)
            -- A support hand belongs on the gun: without the gun's capsules, the holder's hand would only push it off.
            if WGN > 0 then
                gunAt(holder, PX[holder], PY[holder], PZ[holder], LB)
                ridingSet(holder, PX[holder], PY[holder], PZ[holder], LB)
            end
            LA.n = 0
            ridingSet(free, f.x, f.y, f.z, LA)
            local ex, ey, ez = resolveRig(free, LA, LB)
            PX[free], PY[free], PZ[free] = f.x + ex, f.y + ey, f.z + ez
        elseif f then
            PX[free], PY[free], PZ[free] = f.x, f.y, f.z    -- the reload owns it: leave it exactly where tracking says
        end
        HC.pf('body solve')
        -- 2b. NOT THE WORLD. Neither hand stops at a wall or a table any more (2026-11-08): the rays that did it moved the drawn
        -- hand off the controller for every surface near it, and cost the frame. The hands' physics goes to the plugin.
    else
        -- 3. NO WEAPON: each hand against the body, then hand against hand.
        for side = 0, 1 do
            local r0 = RAW[side]
            if r0 and HAND[side] and not SKIP[side] then
                LA.n = 0
                ridingSet(side, r0.x, r0.y, r0.z, LA)
                local dx, dy, dz = resolveRig(side, LA, buildObstacles(side, LB))
                PX[side], PY[side], PZ[side] = r0.x + dx, r0.y + dy, r0.z + dz
            end
        end
        -- Fingers and all: solve the left set against the right set held still, then split the answer between
        -- them. Both are placed from positions that are pure functions of tracking, so this cannot ring, and half
        -- each is what two equal masses meeting would do -- pushing only one would make the same gesture behave
        -- differently depending on which hand you moved.
        if rl and rr and HAND[0] and HAND[1] and not SKIP[0] and not SKIP[1] then
            LA.n = 0; LB.n = 0
            ridingSet(0, PX[0], PY[0], PZ[0], LA)
            ridingSet(1, PX[1], PY[1], PZ[1], LB)
            local dx, dy, dz = resolveRig(0, LA, LB)
            PX[0], PY[0], PZ[0] = PX[0] + dx * 0.5, PY[0] + dy * 0.5, PZ[0] + dz * 0.5
            PX[1], PY[1], PZ[1] = PX[1] - dx * 0.5, PY[1] - dy * 0.5, PZ[1] - dz * 0.5
        end
        -- 4. NOT THE WORLD (see 2b): the hands go through walls and tables as the controllers do.
        FIRM[0], FIRM[1] = false, false
        HC.pf('body solve')
    end

    HC.carryHand()

    -- Publishing, with a limit and a soft release. Past MAX_HOLD the drawn hand is so far from the real one that
    -- keeping it there is worse than letting go -- but letting go in one frame is the snap that reads as a
    -- teleport, so the hold is faded out over RELEASE seconds instead.
    local function send(side)
        if ownHand == side then
            smooth[side], lastStep[side] = nil, nil    -- no accumulated hold to carry back when we take it again
            return 0.0
        end
        local r0 = RAW[side]
        if not r0 then
            VRHandStopModel(side, false, Vector4.new(0, 0, 0, 0))
            smooth[side], lastStep[side] = nil, nil
            return 0.0
        end
        local ox, oy, oz = PX[side] - r0.x, PY[side] - r0.y, PZ[side] - r0.z
        local prev = smooth[side]
        if prev and FIRM[side] and ox * ox + oy * oy + oz * oz >= prev[1] * prev[1] + prev[2] * prev[2] + prev[3] * prev[3] then
            lastStep[side] = nil     -- deeper into the surface: straight there. Coming back out is still eased.
        elseif prev then
            local sx, sy, sz = ox - prev[1], oy - prev[2], oz - prev[3]
            -- SIGN-FLIP DAMPER. A hold whose change reverses direction from one frame to the next is ringing,
            -- not motion, so only part of it is taken; a steady push never reverses and pays nothing.
            local ls = lastStep[side]
            if ls and (sx * ls[1] + sy * ls[2] + sz * ls[3]) < 0.0 then
                sx, sy, sz = sx * 0.35, sy * 0.35, sz * 0.35
                flips[side] = flips[side] + 1
            end
            ls = ls or {}
            ls[1], ls[2], ls[3] = sx, sy, sz
            lastStep[side] = ls
            local k = 1.0 - math.exp(-(dt or 0.016) / SMOOTH_TAU)
            ox, oy, oz = prev[1] + sx * k, prev[2] + sy * k, prev[3] + sz * k
        else
            lastStep[side] = nil
        end
        prev = prev or {}
        prev[1], prev[2], prev[3] = ox, oy, oz
        smooth[side] = prev

        local off = math.sqrt(ox * ox + oy * oy + oz * oz)
        if off > MAX_HOLD then fade[side] = RELEASE end
        local kf = 1.0
        if fade[side] > 0.0 then
            fade[side] = fade[side] - (dt or 0.016)
            kf = math.max(0.0, fade[side]) / RELEASE
            off = off * kf
        end
        VRHandStopModel(side, off > DEAD,
            Vector4.new(r0.x + ox * kf, r0.y + oy * kf, r0.z + oz * kf, 1.0))
        return off
    end

    local offL, offR = send(0), send(1)
    HC.pf('publishing')
    HC.handsPush(pushAllowed and not handBodies, holder, os.clock())
    HC.pf('pushing')
    do
        local wx, wy, wz, wi, wj, wk, wr = worldFrame()
        if wx then
            HC.carry(pushAllowed and math.floor(collMask / 32) % 2 == 1, holder, dt or 0.016, wx, wy, wz, wi, wj, wk, wr)
            HC.debugDraw(holder, wx, wy, wz, wi, wj, wk, wr)
            HC.pf('the view')
        end
    end

    -- Body capsules are switched at the component level; no physical-body handles
    -- survive across a registration or player-state change.
    bodyCapsulesForVehicle(os.clock())

    if t0 then
        local ms = (os.clock() - t0) * 1000.0
        msAcc, msN = msAcc + ms, msN + 1
        if ms > msMax then msMax = ms end
    end

    logAcc = logAcc + (dt or 0.016)
    if logAcc >= 1.0 and dbgOn() then
        logAcc = 0.0
        pcall(function()
            spdlog.info(string.format(
                "[HandColl] holder=%s (grip L=%.3f R=%.3f) caps=%d w=%s slots=%s gun=%d miss=%d pairs<=%d pool=%d solve %.2f/%.2f ms | held L=%.3f R=%.3f"
                .. " | stopped by L=%s>%s R=%s>%s | reversals/s L=%d R=%d",
                tostring(holder), dbgDL, dbgDR, #CAPS,
                lastW and 'yes' or 'no', slotComp and 'yes' or 'no', WGN, wMiss, candMax, poolN,
                (msN > 0) and (msAcc / msN) or -1.0, msMax, offL, offR,
                tostring(worstM[0]), tostring(worstS[0]), tostring(worstM[1]), tostring(worstS[1]),
                flips[0], flips[1]))
        end)
        -- THE RELOAD GATE. Parts whose local translation is moving are the ones the reload animation drives, and
        -- those are exactly the ones a physical reload has to write.
        -- THE CENSUS, reported so the weapon's rigs can be picked out by eye once: entries that only exist
        -- while a gun is in hand, with a small hit count each (four rigs, a few passes a tick).
        if type(VRPoseCensus) == 'function' and censusAt then
            pcall(function()
                -- The two rigs, nominated by the (bones, tracks) pair the pose descriptor carries and
                -- checked against the rig assets: 16 bones and 0 tracks for the frame, 5 and 2 for the magazine.
                local rows = {}
                for w = 0, 1 do
                    rows[#rows + 1] = string.format('%s seen=%d bones=%d tracks=%d buf=%08X%08X',
                        (w == 0) and 'mag' or 'frame',
                        VRRigStatus(0 + w), VRRigStatus(2 + w), VRRigStatus(4 + w),
                        VRRigStatus(8 + w), VRRigStatus(6 + w))
                end
                spdlog.info(string.format("[Rig] weapon=%s | %s",
                    (WGN > 0) and 'yes' or 'no', table.concat(rows, ' | ')))
            end)
        end
        flips[0], flips[1] = 0, 0
        worstM[0], worstS[0], worstM[1], worstS[1] = '-', '-', '-', '-'
        candMax = 0
        msAcc, msMax, msN = 0.0, 0.0, 0
    end
end)

